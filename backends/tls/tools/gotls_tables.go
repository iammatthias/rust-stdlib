// Prints backends/tls/src/tls/tables.rs from Go's crypto/tls cipher suite tables:
//
//	go run backends/tls/tools/gotls_tables.go > backends/tls/src/tls/tables.rs
//
// The tables are Go data (BSD license, see NOTICE); the generator is first-party.
package main

import (
	"crypto/tls"
	"fmt"
	"strings"
)

func versions(vs []uint16) string {
	var s []string
	for _, v := range vs {
		s = append(s, fmt.Sprintf("0x%04x", v))
	}
	return "vec![" + strings.Join(s, ", ") + "]"
}

func main() {
	fmt.Println("// Code generated by backends/tls/tools/gotls_tables.go from Go's crypto/tls; DO NOT EDIT.")
	fmt.Println("// Go is BSD licensed; see NOTICE.")
	fmt.Println()
	fmt.Println("use super::CipherSuite;")
	fmt.Println()
	all := append(tls.CipherSuites(), tls.InsecureCipherSuites()...)
	seen := map[string]bool{}
	for _, c := range all {
		fmt.Printf("pub const %s: u16 = 0x%04x;\n", c.Name, c.ID)
		seen[c.Name] = true
	}
	// Aliases and sentinels that are constants but not table entries.
	fmt.Printf("pub const TLS_ECDHE_RSA_WITH_CHACHA20_POLY1305: u16 = 0x%04x;\n", tls.TLS_ECDHE_RSA_WITH_CHACHA20_POLY1305)
	fmt.Printf("pub const TLS_ECDHE_ECDSA_WITH_CHACHA20_POLY1305: u16 = 0x%04x;\n", tls.TLS_ECDHE_ECDSA_WITH_CHACHA20_POLY1305)
	fmt.Printf("pub const TLS_FALLBACK_SCSV: u16 = 0x%04x;\n", tls.TLS_FALLBACK_SCSV)
	fmt.Println()
	emit := func(name string, list []*tls.CipherSuite) {
		fmt.Printf("pub(super) fn %s() -> Vec<CipherSuite> {\n    vec![\n", name)
		for _, c := range list {
			fmt.Printf("        CipherSuite { id: %s, name: %q.to_string(), supported_versions: %s, insecure: %v },\n",
				c.Name, c.Name, versions(c.SupportedVersions), c.Insecure)
		}
		fmt.Println("    ]\n}")
	}
	emit("secure_suites", tls.CipherSuites())
	fmt.Println()
	emit("insecure_suites", tls.InsecureCipherSuites())
}
