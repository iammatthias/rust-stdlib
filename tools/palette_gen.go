// Generates src/image/color/palette.rs from the local Go toolchain's
// image/color/palette package. Nothing is hand-typed: every entry is read
// from palette.Plan9 and palette.WebSafe at run time.
//
// Usage, from the repository root:
//
//	go run tools/palette_gen.go
//	rustfmt --edition 2021 src/image/color/palette.rs
package main

import (
	"bytes"
	"fmt"
	"image/color"
	"image/color/palette"
	"os"
	"runtime"
)

func table(buf *bytes.Buffer, name string, p color.Palette) {
	fmt.Fprintf(buf, "pub const %s: [Rgba; %d] = [\n", name, len(p))
	for _, c := range p {
		v := c.(color.RGBA)
		if v.A != 0xff {
			panic("palette entry is not opaque")
		}
		fmt.Fprintf(buf, "    rgb(0x%02x, 0x%02x, 0x%02x),\n", v.R, v.G, v.B)
	}
	fmt.Fprintf(buf, "];\n")
}

func main() {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by tools/palette_gen.go from the Go %s sources; DO NOT EDIT.\n", runtime.Version())
	buf.WriteString(`//
// Copyright 2013 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the NOTICE file.

//! Standard color palettes (Go's ` + "`image/color/palette`" + `).
//!
//! ` + "```" + `
//! use rust_stdlib::image::color::palette;
//! assert_eq!(palette::plan9().len(), 256);
//! assert_eq!(palette::web_safe().len(), 216);
//! ` + "```" + `
use super::{Color, Palette, Rgba};

const fn rgb(r: u8, g: u8, b: u8) -> Rgba {
    Rgba { r, g, b, a: 0xff }
}

/// Go's ` + "`palette.Plan9`" + `: 256 opaque colors that dice the RGB cube into
/// 4x4x4 cells with 4 intensity shades in each, as used by Plan 9.
`)
	table(&buf, "PLAN9", palette.Plan9)
	buf.WriteString(`
/// The 216 opaque "web-safe" colors in Go's ` + "`palette.WebSafe`" + ` order:
/// each channel takes the values 0x00, 0x33, ..., 0xff.
`)
	table(&buf, "WEB_SAFE", palette.WebSafe)
	buf.WriteString(`
/// [` + "`PLAN9`" + `] as a [` + "`Palette`" + `] of [` + "`Color::Rgba`" + `] entries.
pub fn plan9() -> Palette {
    Palette(PLAN9.iter().map(|&c| Color::Rgba(c)).collect())
}

/// [` + "`WEB_SAFE`" + `] as a [` + "`Palette`" + `] of [` + "`Color::Rgba`" + `] entries.
pub fn web_safe() -> Palette {
    Palette(WEB_SAFE.iter().map(|&c| Color::Rgba(c)).collect())
}
`)
	if err := os.MkdirAll("src/image/color", 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile("src/image/color/palette.rs", buf.Bytes(), 0o644); err != nil {
		panic(err)
	}
}
