#!/usr/bin/env python3
"""Generate src/encoding/xml/tables.rs from Go's encoding/xml source.

Usage: python3 tools/xml_tables_gen.py > src/encoding/xml/tables.rs
The name-character range tables, HTMLEntity and HTMLAutoClose have no Rust std
equivalent, so they are taken from the Go toolchain (BSD licensed, see NOTICE).
"""
import re
import subprocess

root = subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
src = open(f"{root}/src/encoding/xml/xml.go", encoding="utf-8").read()


def table(name):
    body = src.split(f"var {name} = &unicode.RangeTable{{", 1)[1].split("\n}\n", 1)[0]
    ranges = []
    for lo, hi, stride in re.findall(r"\{([^,{}]+),([^,{}]+),([^{}]+)\}", body):
        lo, hi, stride = (eval(x.strip()) for x in (lo, hi, stride))
        if stride == 1 or lo == hi:
            ranges.append((lo, hi))
        else:
            ranges.extend((c, c) for c in range(lo, hi + 1, stride))
    return ranges


def rust_string(s):
    return '"' + "".join(f"\\u{{{ord(c):04X}}}" for c in s) + '"'


entity_body = src.split("var htmlEntity = map[string]string{", 1)[1].split("\n}\n", 1)[0]
entities = re.findall(r'^\t"([A-Za-z0-9]+)":\s+"((?:\\u[0-9A-F]{4})+)",$', entity_body, re.M)
entities = sorted((k, eval('"' + v + '"')) for k, v in entities)
auto_body = src.split("var htmlAutoClose = []string{", 1)[1].split("\n}\n", 1)[0]
auto = re.findall(r'^\t"([a-z]+)",$', auto_body, re.M)

out = ["// Code generated by tools/xml_tables_gen.py from Go's encoding/xml; DO NOT EDIT.",
       "// Source: Go encoding/xml (BSD-3-Clause), see NOTICE.", ""]
for name, ident in (("first", "FIRST"), ("second", "SECOND")):
    ranges = table(name)
    out.append(f"/// Go's `{name}` name range table ({len(ranges)} ranges).")
    out.append(f"pub(super) static {ident}: [(u32, u32); {len(ranges)}] = [")
    out += [f"    (0x{lo:04X}, 0x{hi:04X})," for lo, hi in ranges]
    out += ["];", ""]
out.append(f"/// Go's `HTMLEntity`: translations for the standard HTML entity characters,\n/// sorted by name ({len(entities)} entries).")
out.append(f"pub static HTML_ENTITY: [(&str, &str); {len(entities)}] = [")
out += [f'    ("{k}", {rust_string(v)}),' for k, v in entities]
out += ["];", ""]
out.append("/// Go's `HTMLAutoClose` list, in Go's order.")
out.append(f"pub static HTML_AUTO_CLOSE: [&str; {len(auto)}] = [")
out += [f'    "{a}",' for a in auto]
out += ["];", ""]
print("\n".join(out))
