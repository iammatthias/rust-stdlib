#!/usr/bin/env python3
"""Generate crates/sys/src/errno_table.rs from Go's syscall tables.

Reads the errno and signal message tables of every zerrors_linux_<arch>.go and
of zerrors_darwin_arm64.go so rust_stdlib_sys prints the same text as Go's
syscall.Errno and syscall.Signal. Go's Linux tables differ by architecture, so
ERRORS_LINUX and SIGNALS_LINUX name the host architecture's table. The
syscall module mirrors linux/amd64 on every host and uses ERRORS_LINUX_AMD64
and SIGNALS_LINUX_AMD64. Run with: python3 tools/gen_sys_errno.py
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates/sys/src/errno_table.rs"

# GOARCH to Rust target_arch. A group of identical tables is named after its
# first GOARCH here; ppc64le shares a target_arch with ppc64. The mips ports
# (Rust tier 3, errno numbers up to 1133) are left out and use amd64's tables.
LINUX_ARCHES = [
    ("amd64", "x86_64"),
    ("386", "x86"),
    ("arm64", "aarch64"),
    ("arm", "arm"),
    ("loong64", "loongarch64"),
    ("riscv64", "riscv64"),
    ("s390x", "s390x"),
    ("ppc64", "powerpc64"),
    ("ppc64le", "powerpc64"),
]


def table(source, name):
    body = re.search(r"var %s = \[\.\.\.\]string\{\n(.*?)\n\}" % name, source, re.S).group(1)
    entries = {}
    for line in body.splitlines():
        m = re.match(r'\s*(\d+):\s+("(?:[^"\\]|\\.)*"),', line)
        if m:
            entries[int(m.group(1))] = m.group(2)
    return entries


def render(const, entries):
    size = max(entries) + 1
    lines = [f"pub const {const}: [&str; {size}] = ["]
    for i in range(size):
        lines.append(f"    {entries.get(i, chr(34) * 2)},")
    lines.append("];")
    return "\n".join(lines)


def linux_tables(goroot, name, prefix):
    """Render each distinct table once and alias the host's as `prefix`."""
    groups = {}
    arch_of = {}
    for goarch, rust_arch in LINUX_ARCHES:
        entries = table((goroot / f"src/syscall/zerrors_linux_{goarch}.go").read_text(), name)
        key = tuple(sorted(entries.items()))
        group = groups.setdefault(key, (f"{prefix}_{goarch.upper()}", entries, []))
        if rust_arch in arch_of and arch_of[rust_arch] != group[0]:
            raise SystemExit(f"{name}: {goarch} differs from the other {rust_arch} table")
        arch_of[rust_arch] = group[0]
        if rust_arch not in group[2]:
            group[2].append(rust_arch)
    out = []
    for const, entries, _ in groups.values():
        out += [render(const, entries), ""]
    amd64 = f"{prefix}_AMD64"
    if len(groups) == 1:
        return out + [f"pub use {amd64} as {prefix};", ""]
    for const, _, arches in groups.values():
        if const == amd64:
            # Architectures not listed above fall back to amd64.
            arches = [a for a in arch_of if arch_of[a] != amd64]
        cfg = ", ".join(f'target_arch = "{a}"' for a in arches)
        cfg = f"any({cfg})" if len(arches) > 1 else cfg
        if const == amd64:
            cfg = f"not({cfg})"
        out += [f"#[cfg({cfg})]", f"pub use {const} as {prefix};", ""]
    return out


def main():
    goroot = Path(subprocess.check_output(["go", "env", "GOROOT"], text=True).strip())
    out = ["//! Generated by tools/gen_sys_errno.py from Go's syscall tables. Do not edit.", "#![allow(dead_code, unused_imports)]", ""]
    out += linux_tables(goroot, "errors", "ERRORS_LINUX")
    out += linux_tables(goroot, "signals", "SIGNALS_LINUX")
    source = (goroot / "src/syscall/zerrors_darwin_arm64.go").read_text()
    out += [render("ERRORS_DARWIN", table(source, "errors")), ""]
    out += [render("SIGNALS_DARWIN", table(source, "signals")), ""]
    OUT.write_text("\n".join(out))
    subprocess.run(["rustfmt", "--edition", "2021", str(OUT)], check=True)


if __name__ == "__main__":
    main()
