#!/usr/bin/env python3
"""Extract the table-driven cases of Go's path/filepath tests into
tests/fixtures/filepath_tables.rs (Unix variants only).

Rows containing byte strings that are not valid UTF-8 are skipped: Rust paths
here are `&str`.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GOROOT = subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
SRC = Path(GOROOT) / "src/path/filepath"


def tokenize(text):
    toks = []
    i = 0
    while i < len(text):
        c = text[i]
        if c in " \t\r\n":
            i += 1
        elif text.startswith("//", i):
            while i < len(text) and text[i] != "\n":
                i += 1
        elif c == '"':
            j = i + 1
            raw = bytearray()
            while text[j] != '"':
                if text[j] == "\\":
                    e = text[j + 1]
                    if e == "x":
                        raw.append(int(text[j + 2:j + 4], 16))
                        j += 4
                        continue
                    if e in "01234567":
                        raw.append(int(text[j + 1:j + 4], 8))
                        j += 4
                        continue
                    if e == "u":
                        raw += chr(int(text[j + 2:j + 6], 16)).encode()
                        j += 6
                        continue
                    raw += {"n": b"\n", "t": b"\t", "r": b"\r", "\\": b"\\", '"': b'"', "'": b"'", "a": b"\a",
                            "b": b"\b", "f": b"\f", "v": b"\v"}[e]
                    j += 2
                else:
                    raw += text[j].encode()
                    j += 1
            toks.append(("s", bytes(raw)))
            i = j + 1
        elif c == "`":
            j = text.index("`", i + 1)
            toks.append(("s", text[i + 1:j].encode()))
            i = j + 1
        elif c in "{},":
            toks.append((c, c))
            i += 1
        else:
            m = re.match(r"[A-Za-z_][A-Za-z_0-9.]*|-?[0-9]+", text[i:])
            if not m:
                raise ValueError(f"bad token at {text[i:i+20]!r}")
            toks.append(("id", m.group(0)))
            i += len(m.group(0))
    return toks


def parse_rows(body):
    """Parse `{...}, {...}` rows into nested lists."""
    toks = tokenize(body)
    pos = 0

    def value():
        nonlocal pos
        kind, v = toks[pos]
        if kind == "{":
            pos += 1
            items = []
            while toks[pos][0] != "}":
                items.append(value())
                if toks[pos][0] == ",":
                    pos += 1
            pos += 1
            return items
        if kind == "id" and v == "[]string" or (kind == "id" and v.startswith("[]")):
            pos += 1
            return value()
        pos += 1
        return v if kind == "s" else ("id", v)

    rows = []
    while pos < len(toks):
        rows.append(value())
        if pos < len(toks) and toks[pos][0] == ",":
            pos += 1
    return rows


def table(src, name):
    m = re.search(r"var %s = \[\]\w+\{\n(.*?)\n\}\n" % re.escape(name), src, re.S)
    if not m:
        raise KeyError(name)
    body = m.group(1)
    # `[]string{...}` elements: drop the type name so the tokenizer sees `{`.
    body = body.replace("[]string", "")
    return parse_rows(body)


def rs(b):
    s = b.decode("utf-8")
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def emit_strs(rows, ncols):
    out = []
    for r in rows:
        try:
            out.append("        (" + ", ".join(rs(x) for x in r[:ncols]) + "),")
        except UnicodeDecodeError:
            continue
    return out


def main():
    p = (SRC / "path_test.go").read_text()
    m = (SRC / "match_test.go").read_text()
    out = ["// Generated by tools/gen_filepath_tables.py from Go's path/filepath tests (BSD license, see NOTICE).",
           "// Unix variants only; rows with invalid UTF-8 are skipped.", ""]

    def fn(name, ret, lines):
        out.append(f"pub fn {name}() -> Vec<{ret}> {{\n    vec![")
        out.extend(lines)
        out.append("    ]\n}\n")

    clean = table(p, "cleantests") + table(p, "nonwincleantests")
    fn("clean_tests", "(&'static str, &'static str)", emit_strs(clean, 2))
    il = [r for r in table(p, "islocaltests")]
    fn("is_local_tests", "(&'static str, bool)",
       [f"        ({rs(r[0])}, {r[1][1]})," for r in il])
    lz = table(p, "localizetests") + table(p, "unixlocalizetests")
    lines = []
    for r in lz:
        try:
            lines.append(f"        ({rs(r[0])}, {rs(r[1])}),")
        except UnicodeDecodeError:
            pass
    fn("localize_tests", "(&'static str, &'static str)", lines)
    fn("split_tests", "(&'static str, &'static str, &'static str)", emit_strs(table(p, "unixsplittests"), 3))
    jt = table(p, "jointests") + table(p, "nonwinjointests")
    lines = []
    for r in jt:
        items = ", ".join(rs(x) for x in r[0])
        lines.append(f"        (vec![{items}], {rs(r[1])}),")
    fn("join_tests", "(Vec<&'static str>, &'static str)", lines)
    fn("ext_tests", "(&'static str, &'static str)", emit_strs(table(p, "exttests"), 2))
    fn("base_tests", "(&'static str, &'static str)", emit_strs(table(p, "basetests"), 2))
    fn("dir_tests", "(&'static str, &'static str)",
       emit_strs(table(p, "dirtests") + table(p, "nonwindirtests"), 2))
    fn("is_abs_tests", "(&'static str, bool)",
       [f"        ({rs(r[0])}, {r[1][1]})," for r in table(p, "isabstests")])
    fn("rel_tests", "(&'static str, &'static str, &'static str)", emit_strs(table(p, "reltests"), 3))
    lines = []
    for r in table(m, "matchTests"):
        err = "true" if r[3] == ("id", "ErrBadPattern") else "false"
        lines.append(f"        ({rs(r[0])}, {rs(r[1])}, {r[2][1]}, {err}),")
    fn("match_tests", "(&'static str, &'static str, bool, bool)", lines)
    dest = ROOT / "tests/fixtures/filepath_tables.rs"
    dest.write_text("\n".join(out))
    print(f"wrote {dest}")


if __name__ == "__main__":
    sys.exit(main())
