#!/usr/bin/env python3
"""Generate src/net/http/h2/hpack_tables.rs from Go's vendored x/net hpack tables."""
import re
import subprocess
import sys

goroot = subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
base = goroot + "/src/vendor/golang.org/x/net/http2/hpack/"
tables = open(base + "tables.go").read()
static = open(base + "static_table.go").read()


def array(name):
    m = re.search(r"var %s = \[256\]\w+\{(.*?)\n\}" % name, tables, re.S)
    body = "\n".join(l for l in m.group(1).split("\n") if not l.strip().startswith("//"))
    vals = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
    assert len(vals) == 256, (name, len(vals))
    return vals


codes = array("huffmanCodes")
lens = array("huffmanCodeLen")
entries = {}
for m in re.finditer(r'\{name: "([^"]*)", value: "([^"]*)"\}:\s*(\d+),', static):
    entries[int(m.group(3))] = (m.group(1), m.group(2))
assert sorted(entries) == list(range(1, 62))

out = ["// Code generated by tools/gen_hpack_tables.py from Go's x/net/http2/hpack; DO NOT EDIT.",
       "// Go source: BSD-3-Clause, Copyright 2014 The Go Authors (see NOTICE).", ""]
out.append("/// RFC 7541 appendix B Huffman codes for the 256 byte symbols.")
out.append("pub(crate) const HUFFMAN_CODES: [u32; 256] = [")
for i in range(0, 256, 8):
    out.append("    " + ", ".join(codes[i:i + 8]) + ",")
out.append("];")
out.append("")
out.append("/// Bit lengths matching [`HUFFMAN_CODES`].")
out.append("pub(crate) const HUFFMAN_CODE_LEN: [u8; 256] = [")
for i in range(0, 256, 16):
    out.append("    " + ", ".join(lens[i:i + 16]) + ",")
out.append("];")
out.append("")
out.append("/// RFC 7541 appendix A static table (index 1 first).")
out.append("pub(crate) const STATIC_TABLE: [(&str, &str); 61] = [")
for i in range(1, 62):
    n, v = entries[i]
    out.append('    ("%s", "%s"),' % (n, v))
out.append("];")
open(sys.argv[1], "w").write("\n".join(out) + "\n")

if len(sys.argv) > 2:
    # HTTP/2 prohibited TLS 1.2 cipher suites (RFC 9113 appendix A), from net/http/internal/http2/ciphers.go.
    src = open(goroot + "/src/net/http/internal/http2/ciphers.go").read()
    consts = {m.group(1): int(m.group(2), 16)
              for m in re.finditer(r"(cipher_TLS_\w+)\s+uint16 = (0x[0-9A-Fa-f]+)", src)}
    body = src[src.index("func isBadCipher"):]
    names = re.findall(r"cipher_TLS_\w+", body[:body.index("return true")])
    values = sorted({consts[n] for n in names})
    lines = ["// Code generated by tools/gen_hpack_tables.py from Go's net/http/internal/http2/ciphers.go; DO NOT EDIT.",
             "// Go source: BSD-3-Clause, Copyright 2014 The Go Authors (see NOTICE).", "",
             "/// TLS 1.2 cipher suites HTTP/2 prohibits (Go's `isBadCipher`), sorted.",
             "pub(crate) const BAD_CIPHERS: [u16; %d] = [" % len(values)]
    for i in range(0, len(values), 8):
        lines.append("    " + ", ".join("0x%04x" % v for v in values[i:i + 8]) + ",")
    lines.append("];")
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")
