// Generate src/unicode/tables.rs from Go's own unicode package, so the data is
// bit-identical to Go's Unicode version (not Rust's, which may differ).
//
// Usage: go run tools/unicode_gen.go > src/unicode/tables.rs
//
// Exported table variables are discovered by parsing GOROOT/src/unicode/tables.go
// (Go has no way to enumerate package variables); their values come from the
// compiled unicode package. The unexported fold data (asciiFold, caseOrbit) is
// reconstructed through SimpleFold: an entry is recorded exactly where the
// orbit overrides the plain lower/upper rule, which is observably identical.
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"unicode"
)

type namer struct {
	byPtr map[*unicode.RangeTable]string
	order []*unicode.RangeTable
}

func (n *namer) add(name string, t *unicode.RangeTable) {
	if _, ok := n.byPtr[t]; !ok {
		n.byPtr[t] = name
		n.order = append(n.order, t)
	}
}

func sortedKeys(m map[string]*unicode.RangeTable) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func main() {
	fset := token.NewFileSet()
	src := filepath.Join(runtime.GOROOT(), "src", "unicode", "tables.go")
	file, err := parser.ParseFile(fset, src, nil, 0)
	if err != nil {
		panic(err)
	}
	// Exported `Name = _Private` aliases of range tables.
	aliases := map[string]string{}
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.VAR {
			continue
		}
		for _, spec := range gd.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, name := range vs.Names {
				if !name.IsExported() || i >= len(vs.Values) {
					continue
				}
				if id, ok := vs.Values[i].(*ast.Ident); ok && strings.HasPrefix(id.Name, "_") {
					aliases[name.Name] = id.Name[1:]
				}
			}
		}
	}

	namers := &namer{byPtr: map[*unicode.RangeTable]string{}}
	lookup := map[string]*unicode.RangeTable{}
	for _, m := range []map[string]*unicode.RangeTable{unicode.Categories, unicode.Scripts, unicode.Properties} {
		for _, k := range sortedKeys(m) {
			lookup[k] = m[k]
			namers.add(strings.ToUpper(k), m[k])
		}
	}
	for _, k := range sortedKeys(unicode.FoldCategory) {
		namers.add("FOLD_"+strings.ToUpper(k), unicode.FoldCategory[k])
	}
	for _, k := range sortedKeys(unicode.FoldScript) {
		namers.add("FOLD_"+strings.ToUpper(k), unicode.FoldScript[k])
	}

	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("// Code generated by tools/unicode_gen.go from Go %s; DO NOT EDIT.\n", runtime.Version())
	p("//\n// Unicode %s, copied from Go's unicode package (BSD-3-Clause, see NOTICE).\n\n", unicode.Version)
	p("use super::{CaseRange, Range16, Range32, RangeTable, SpecialCase};\n\n")
	p("pub const VERSION: &str = %q;\n\n", unicode.Version)
	p("const fn r16(lo: u16, hi: u16, stride: u16) -> Range16 {\n    Range16 { lo, hi, stride }\n}\n\n")
	p("const fn r32(lo: u32, hi: u32, stride: u32) -> Range32 {\n    Range32 { lo, hi, stride }\n}\n\n")
	p("const fn cr(lo: u32, hi: u32, upper: i32, lower: i32, title: i32) -> CaseRange {\n    CaseRange { lo, hi, delta: [upper, lower, title] }\n}\n\n")

	// Table data.
	for _, t := range namers.order {
		name := namers.byPtr[t]
		p("static T_%s: RangeTable = RangeTable {\n    r16: &[", name)
		for i, r := range t.R16 {
			if i%4 == 0 {
				p("\n        ")
			} else {
				p(" ")
			}
			p("r16(0x%X, 0x%X, %d),", r.Lo, r.Hi, r.Stride)
		}
		p("\n    ],\n    r32: &[")
		for i, r := range t.R32 {
			if i%4 == 0 {
				p("\n        ")
			} else {
				p(" ")
			}
			p("r32(0x%X, 0x%X, %d),", r.Lo, r.Hi, r.Stride)
		}
		p("\n    ],\n    latin_offset: %d,\n};\n\n", t.LatinOffset)
	}

	// Exported variables: Go's names upper-cased, plus the Go-named aliases.
	exported := sortedAliasNames(aliases)
	for _, name := range exported {
		t, ok := lookup[aliases[name]]
		if !ok {
			// Not a range table (CaseRanges, TurkishCase, ...): emitted separately.
			fmt.Fprintf(os.Stderr, "skipping non-table alias %s\n", name)
			continue
		}
		p("pub static %s: &RangeTable = &T_%s;\n", strings.ToUpper(name), namers.byPtr[t])
	}
	p("\n")

	tableMap := func(rust string, m map[string]*unicode.RangeTable) {
		p("pub static %s: &[(&str, &RangeTable)] = &[\n", rust)
		for _, k := range sortedKeys(m) {
			p("    (%q, &T_%s),\n", k, namers.byPtr[m[k]])
		}
		p("];\n\n")
	}
	tableMap("CATEGORIES", unicode.Categories)
	tableMap("SCRIPTS", unicode.Scripts)
	tableMap("PROPERTIES", unicode.Properties)
	for _, pair := range []struct {
		rust string
		m    map[string]*unicode.RangeTable
	}{{"FOLD_CATEGORY", unicode.FoldCategory}, {"FOLD_SCRIPT", unicode.FoldScript}} {
		p("pub static %s: &[(&str, &RangeTable)] = &[\n", pair.rust)
		for _, k := range sortedKeys(pair.m) {
			p("    (%q, &T_%s),\n", k, namers.byPtr[pair.m[k]])
		}
		p("];\n\n")
	}

	keys := make([]string, 0)
	for k := range unicode.CategoryAliases {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	p("pub static CATEGORY_ALIASES: &[(&str, &str)] = &[\n")
	for _, k := range keys {
		p("    (%q, %q),\n", k, unicode.CategoryAliases[k])
	}
	p("];\n\n")

	p("pub static GRAPHIC_RANGES: &[&RangeTable] = &[%s];\n\n", tableList(unicode.GraphicRanges, namers))
	p("pub static PRINT_RANGES: &[&RangeTable] = &[%s];\n\n", tableList(unicode.PrintRanges, namers))

	caseRanges := func(rs []unicode.CaseRange) {
		for _, c := range rs {
			p("    cr(0x%X, 0x%X, %d, %d, %d),\n", c.Lo, c.Hi, c.Delta[0], c.Delta[1], c.Delta[2])
		}
	}
	p("pub static CASE_RANGES: &[CaseRange] = &[\n")
	caseRanges(unicode.CaseRanges)
	p("];\n\n")
	p("pub static TURKISH_CASE: SpecialCase<'static> = SpecialCase(&[\n")
	caseRanges(unicode.TurkishCase)
	p("]);\n\n")
	p("pub static AZERI_CASE: SpecialCase<'static> = SpecialCase(&[\n")
	caseRanges(unicode.AzeriCase)
	p("]);\n\n")

	// SimpleFold data.
	p("pub(super) static ASCII_FOLD: [u16; 128] = [")
	for r := rune(0); r < 128; r++ {
		if r%16 == 0 {
			p("\n    ")
		} else {
			p(" ")
		}
		p("0x%X,", unicode.SimpleFold(r))
	}
	p("\n];\n\n")
	p("pub(super) static CASE_ORBIT: &[(u16, u16)] = &[")
	n := 0
	for r := rune(128); r <= unicode.MaxRune; r++ {
		def := unicode.ToLower(r)
		if def == r {
			def = unicode.ToUpper(r)
		}
		f := unicode.SimpleFold(r)
		if f == def {
			continue
		}
		if r > 0xFFFF || f > 0xFFFF {
			panic(fmt.Sprintf("orbit entry %U -> %U does not fit u16", r, f))
		}
		if n%4 == 0 {
			p("\n    ")
		} else {
			p(" ")
		}
		n++
		p("(0x%X, 0x%X),", r, f)
	}
	p("\n];\n")
	os.Stdout.WriteString(b.String())
}

func sortedAliasNames(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func tableList(ts []*unicode.RangeTable, n *namer) string {
	names := make([]string, len(ts))
	for i, t := range ts {
		names[i] = "&T_" + n.byPtr[t]
	}
	return strings.Join(names, ", ")
}
