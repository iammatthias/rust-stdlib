// Extracts the known-answer tables from Go's crypto/cipher, crypto/aes,
// crypto/des and crypto/rc4 tests into the tab-separated fixtures in
// crates/crypto/tests/fixtures.
//
// Usage: go run tools/crypto_cipher_vectors_gen.go OUTDIR
//
// Each fixture line is one table row; fields are tab-separated and typed as in
// tools/crypto_vectors_gen.go: s:HEX for strings and byte slices. Go's tables
// refer to shared variables (commonKey128, tableA1Key, ...); those are
// resolved across the package's test files. The tables are Go's (BSD-licensed,
// see NOTICE).
package main

import (
	"encoding/hex"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
)

type table struct {
	dir, variable, out string
}

var tables = []table{
	{"crypto/aes", "encryptTests", "aes.tsv"},
	{"crypto/des", "encryptDESTests", "des.tsv"},
	{"crypto/des", "weakKeyTests", "des_weak.tsv"},
	{"crypto/des", "semiWeakKeyTests", "des_semiweak.tsv"},
	{"crypto/des", "encryptTripleDESTests", "tdes.tsv"},
	{"crypto/des", "tableA1Tests", "des_a1.tsv"},
	{"crypto/des", "tableA2Tests", "des_a2.tsv"},
	{"crypto/des", "tableA3Tests", "des_a3.tsv"},
	{"crypto/des", "tableA4Tests", "des_a4.tsv"},
	{"crypto/rc4", "golden", "rc4.tsv"},
	{"crypto/cipher", "cbcAESTests", "cbc_aes.tsv"},
	{"crypto/cipher", "cfbTests", "cfb.tsv"},
	{"crypto/cipher", "ctrAESTests", "ctr_aes.tsv"},
	{"crypto/cipher", "ofbTests", "ofb.tsv"},
	{"crypto/cipher", "aesGCMTests", "gcm.tsv"},
}

// Single values the tables mention by name, such as the shared AES keys.
var singles = []struct{ dir, variable, out string }{
	{"crypto/cipher", "commonInput", "common_input.tsv"},
	{"crypto/des", "tableA1Key", "des_a1_key.tsv"},
	{"crypto/des", "tableA2Plaintext", "des_a2_plaintext.tsv"},
	{"crypto/des", "tableA3Plaintext", "des_a3_plaintext.tsv"},
}

type pkg struct {
	vars map[string]ast.Expr
}

func load(root, dir string) *pkg {
	p := &pkg{vars: map[string]ast.Expr{}}
	files, err := filepath.Glob(filepath.Join(root, dir, "*_test.go"))
	must(err)
	for _, name := range files {
		file, err := parser.ParseFile(token.NewFileSet(), name, nil, 0)
		must(err)
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.VAR {
				continue
			}
			for _, spec := range gen.Specs {
				v := spec.(*ast.ValueSpec)
				if len(v.Names) == 1 && len(v.Values) == 1 {
					p.vars[v.Names[0].Name] = v.Values[0]
				}
			}
		}
	}
	return p
}

func (p *pkg) field(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.BasicLit:
		switch e.Kind {
		case token.STRING:
			s, err := strconv.Unquote(e.Value)
			must(err)
			return "s:" + hex.EncodeToString([]byte(s))
		case token.INT:
			return "i:" + e.Value
		}
	case *ast.CompositeLit: // []byte{0x01, ...}
		var b []byte
		for _, element := range e.Elts {
			n, err := strconv.ParseUint(element.(*ast.BasicLit).Value, 0, 8)
			must(err)
			b = append(b, byte(n))
		}
		return "s:" + hex.EncodeToString(b)
	case *ast.Ident:
		if e.Name == "nil" {
			return "s:"
		}
		if value, ok := p.vars[e.Name]; ok {
			return p.field(value)
		}
	case *ast.CallExpr: // []byte("...")
		return p.field(e.Args[0])
	}
	panic(fmt.Sprintf("unsupported expression %T: %v", expr, expr))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func main() {
	out := os.Args[1]
	root := filepath.Join(runtime.GOROOT(), "src")
	packages := map[string]*pkg{}
	get := func(dir string) *pkg {
		if packages[dir] == nil {
			packages[dir] = load(root, dir)
		}
		return packages[dir]
	}
	for _, t := range tables {
		p := get(t.dir)
		list, ok := p.vars[t.variable]
		if !ok {
			panic("missing table " + t.variable)
		}
		var rows []string
		for _, row := range list.(*ast.CompositeLit).Elts {
			var fields []string
			for _, element := range row.(*ast.CompositeLit).Elts {
				fields = append(fields, p.field(element))
			}
			rows = append(rows, strings.Join(fields, "\t"))
		}
		header := fmt.Sprintf("# From Go %s %s (BSD-licensed, see NOTICE); generated by tools/crypto_cipher_vectors_gen.go\n", t.dir, t.variable)
		must(os.WriteFile(filepath.Join(out, t.out), []byte(header+strings.Join(rows, "\n")+"\n"), 0o644))
		fmt.Printf("%s: %d rows\n", t.out, len(rows))
	}
	for _, s := range singles {
		p := get(s.dir)
		header := fmt.Sprintf("# From Go %s %s (BSD-licensed, see NOTICE); generated by tools/crypto_cipher_vectors_gen.go\n", s.dir, s.variable)
		must(os.WriteFile(filepath.Join(out, s.out), []byte(header+p.field(p.vars[s.variable])+"\n"), 0o644))
	}
}
