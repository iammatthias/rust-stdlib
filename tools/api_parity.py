#!/usr/bin/env python3
"""Symbol-level Go API parity scoreboard.

Ground truth is docs/api/go-surface.json: every exported symbol of every
in-scope Go package, generated by tools/api_surface.go. Each package may have a
mapping file docs/api/<package with / as _>.json:

    {"package": "encoding/hex",
     "symbols": {
        "EncodeToString": {"rust": "rust_stdlib::encoding::hex::encode"},
        "Dumper": {"deviation": "reason-code", "note": "why Rust cannot express it"},
        "Buffer.String": {"rust": "...", "deviation": "reason-code", "note": "the closest Rust item and what it cannot express"},
        "Decode": {"rust": "...", "differs": "reason-code", "note": "how behaviour differs"},
        ...}}

A "rust" entry is a path to any Rust item (function, type, method, field,
constant, trait item, or a std item such as `str::split_whitespace`). It is
verified as a rustdoc intra-doc link in the generated, doc-only module
src/api_surface.rs; `cargo rustdoc` denies broken links. Paths starting with
`rust_stdlib_crypto::` or `rust_stdlib_tls::` belong to those crates and are verified the
same way in crates/crypto/src/api_surface.rs and backends/tls/src/api_surface.rs
(rustdoc runs for every crate). Entries with
"auto": true were guessed by --bootstrap and still need review; they count as
mapped because they compile, but are reported separately.

Statuses are computed, never hand-written:
  complete     every symbol has a reviewed mapping or a documented deviation, and no
               mapping is marked "differs"
  partial      some symbols are accounted for
  planned      none are
  out-of-scope Go compiler/runtime/tooling packages (not in the surface)

Commands:
  api_parity.py              regenerate src/api_surface.rs, docs/coverage.json, docs/COVERAGE.md
  api_parity.py --links      also run rustdoc to prove every mapped path resolves
  api_parity.py --check      fail if a generated file is stale, a mapping is invalid
                             or a mapped Rust path does not resolve (used by tools/check.py)
  api_parity.py --surface    regenerate docs/api/go-surface.json with the local Go toolchain
  api_parity.py --bootstrap PKG=rust::module ...
                             guess snake_case mappings for PKG under the module and keep
                             only those that compile (marked "auto")
"""
import collections
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
API = ROOT / "docs/api"
SURFACE = API / "go-surface.json"
GENERATED_TEST = ROOT / "src/api_surface.rs"
CRATE = "rust_stdlib::"
# Root-crate modules compiled only on Unix (`#[cfg(unix)]` in src/lib.rs and
# src/path.rs). Their links are generated under `#[cfg(unix)]`.
UNIX_ONLY_MODULES = ("os", "path::filepath")
# Mappings into the separate first-party crates (docs/adr/0002, 0003) are
# verified by rustdoc in those crates, routed by path prefix.
SURFACES = (
    # (key, crate prefix, generated module, manifest or None for the root)
    ("root", CRATE, GENERATED_TEST, None),
    ("crypto", "rust_stdlib_crypto::", ROOT / "crates/crypto/src/api_surface.rs", "crates/crypto/Cargo.toml"),
    ("tls", "rust_stdlib_tls::", ROOT / "backends/tls/src/api_surface.rs", "backends/tls/Cargo.toml"),
    ("sys", "rust_stdlib_sys::", ROOT / "crates/sys/src/api_surface.rs", "crates/sys/Cargo.toml"),
)


def out_of_scope(package):
    return package in {"builtin", "unsafe", "structs"} or package.startswith(("go/", "runtime", "debug/"))


def go_env():
    env = os.environ.copy()
    env.update({"GOTOOLCHAIN": "local", "GOPROXY": "off", "GOSUMDB": "off"})
    return env


def public_packages():
    listed = subprocess.check_output(["go", "list", "std"], text=True, env=go_env()).splitlines()
    return sorted(p for p in listed if "internal" not in p.split("/") and not p.startswith("vendor/"))


def regenerate_surface():
    packages = [p for p in public_packages() if not out_of_scope(p)]
    output = subprocess.check_output(["go", "run", str(ROOT / "tools/api_surface.go")],
                                     input="\n".join(packages) + "\n", text=True, env=go_env())
    data = json.loads(output)
    data["out_of_scope"] = [p for p in public_packages() if out_of_scope(p)]
    SURFACE.write_text(json.dumps(data, indent=1) + "\n")
    print(f"{data['go_version']}: {len(data['packages'])} packages, "
          f"{sum(len(v) for v in data['packages'].values())} symbols")


def mapping_path(package):
    return API / (package.replace("/", "_") + ".json")


def load_surface():
    return json.loads(SURFACE.read_text())


def load_mappings(surface):
    mappings, errors = {}, []
    for path in sorted(API.glob("*.json")):
        if path == SURFACE:
            continue
        data = json.loads(path.read_text())
        package = data.get("package")
        if package not in surface["packages"]:
            errors.append(f"{path.name}: unknown or out-of-scope package {package!r}")
            continue
        if path != mapping_path(package):
            errors.append(f"{path.name}: expected file name {mapping_path(package).name}")
        known = {s["name"] for s in surface["packages"][package]}
        for name, entry in data.get("symbols", {}).items():
            if name not in known:
                errors.append(f"{package}: {name} is not an exported Go symbol")
            elif "rust" not in entry and "deviation" not in entry:
                errors.append(f"{package}: {name} needs 'rust', 'deviation', or both")
            elif "deviation" in entry and "differs" in entry:
                errors.append(f"{package}: {name} cannot be both 'deviation' and 'differs'")
            elif "rust" in entry and not entry["rust"].strip():
                errors.append(f"{package}: {name} has an empty Rust path")
            elif "deviation" in entry and not entry.get("note", "").strip():
                errors.append(f"{package}: {name} deviation needs a note")
            elif "differs" in entry and ("rust" not in entry or not entry.get("note", "").strip()):
                errors.append(f"{package}: {name} 'differs' needs a 'rust' path and a note")
        mappings[package] = data
    return mappings, errors


def surface_of(path):
    """Which generated module verifies a mapped path: by crate prefix."""
    for key, prefix, _, _ in SURFACES:
        if path.startswith(prefix):
            return key
    return "root"


def link_target(path):
    for _, prefix, _, _ in SURFACES:
        if path.startswith(prefix):
            return "crate::" + path[len(prefix):]
    return path


def unix_only(path):
    """Whether a mapped path goes through a module that exists only on Unix."""
    rest = path[len(CRATE):] if path.startswith(CRATE) else ""
    return any(rest == m or rest.startswith(m + "::") for m in UNIX_ONLY_MODULES)


def render_test(surface, mappings, key="root"):
    """Doc-only links for one surface. Links into Unix-only modules go in a
    `#[cfg(unix)]` block so rustdoc on other platforms never resolves them."""
    lines = ["#![deny(rustdoc::broken_intra_doc_links)]",
             "//! Go API surface map, generated by tools/api_parity.py from docs/api/*.json.",
             "//!",
             "//! Do not edit. Compiled only by rustdoc; every link below must resolve,",
             "//! which proves the mapped Rust item for each Go symbol exists."]
    origins = {}
    for unix in (False, True):
        block = []
        for package in sorted(mappings):
            entries = [(n, e) for n, e in sorted(mappings[package]["symbols"].items())
                       if "rust" in e and surface_of(e["rust"]) == key and unix_only(e["rust"]) == unix]
            if not entries:
                continue
            block += [("//!", None), (f"//! ## `{package}`", None), ("//!", None)]
            block += [(f"//! - [`{name}`]({link_target(entry['rust'])})", (package, name))
                      for name, entry in entries]
        if not block:
            continue
        indent = ""
        if unix:
            lines += ["#[cfg(unix)]", "mod unix {"]
            indent = "    "
        for text, origin in block:
            if origin:
                origins[len(lines) + 1] = origin
            lines.append(indent + text)
        if unix:
            lines.append("}")
    return "\n".join(lines) + "\n", origins


def tally(surface, mappings):
    rows = []
    for package in sorted(set(surface["packages"]) | set(surface["out_of_scope"])):
        if package in surface["out_of_scope"]:
            rows.append({"go_package": package, "status": "out-of-scope", "symbols": 0})
            continue
        symbols = surface["packages"].get(package, [])
        entries = mappings.get(package, {}).get("symbols", {})
        rust = sum(1 for e in entries.values() if "rust" in e and "deviation" not in e)
        auto = sum(1 for e in entries.values() if "rust" in e and e.get("auto"))
        deviations = sum(1 for e in entries.values() if "deviation" in e)
        differs = sum(1 for e in entries.values() if "rust" in e and "differs" in e)
        total = len(symbols)
        accounted = rust + deviations
        if accounted == total and auto == 0 and differs == 0:
            status = "complete"
        elif accounted:
            status = "partial"
        else:
            status = "planned"
        row = {"go_package": package, "status": status, "symbols": total, "mapped": rust,
               "unreviewed": auto, "differs": differs, "deviations": deviations,
               "missing": total - accounted}
        note = mappings.get(package, {}).get("notes")
        if note:
            row["notes"] = note
        rows.append(row)
    return rows


def render_coverage(surface, rows, codes):
    in_scope = [r for r in rows if r["status"] != "out-of-scope"]
    total = sum(r["symbols"] for r in in_scope)
    mapped = sum(r["mapped"] for r in in_scope)
    auto = sum(r["unreviewed"] for r in in_scope)
    deviations = sum(r["deviations"] for r in in_scope)
    differs = sum(r["differs"] for r in in_scope)
    counts = collections.Counter(r["status"] for r in rows)
    data = {"inventory_toolchain": surface["go_version"],
            "coverage_claim": "symbol-level: a symbol counts only if its Rust mapping compiles or its deviation is documented",
            "totals": {"symbols": total, "mapped": mapped, "unreviewed": auto, "differs": differs,
                       "deviations": deviations, "missing": total - mapped - deviations},
            "package_status": dict(sorted(counts.items())),
            "deviation_codes": dict(sorted(codes.items(), key=lambda kv: (-kv[1], kv[0]))),
            "packages": rows}
    text = ["# Go API parity", "",
            f"Surface: every exported symbol of the in-scope Go {surface['go_version']} packages "
            "(linux/amd64), from `docs/api/go-surface.json`. A symbol counts only when its "
            "Rust mapping in `docs/api/<package>.json` compiles (`tests/api_surface.rs`) "
            "or it has a documented deviation. Behavioural equivalence is checked "
            "separately by the Go differential suites.", "",
            "Regenerate with `python3 tools/api_parity.py`.", "",
            f"**{mapped + deviations} / {total} symbols accounted for "
            f"({100 * (mapped + deviations) / total:.1f}%)**: {mapped} mapped "
            f"({auto} unreviewed bootstrap guesses, {differs} with known behaviour differences), "
            f"{deviations} documented deviations, "
            f"{total - mapped - deviations} missing.", "",
            "Packages: " + ", ".join(f"{counts[k]} {k}" for k in ("complete", "partial", "planned", "out-of-scope")) + ".", "",
            "| Go package | Status | Mapped | Unreviewed | Differs | Deviations | Missing | Total |",
            "|---|---|---:|---:|---:|---:|---:|---:|"]
    for r in rows:
        if r["status"] == "out-of-scope":
            continue
        text.append(f"| `{r['go_package']}` | {r['status']} | {r['mapped']} | {r['unreviewed']} | {r['differs']} | "
                    f"{r['deviations']} | {r['missing']} | {r['symbols']} |")
    text += ["", "## Deviations by code", "",
             "A combined code such as `a+b` counts toward each part. The meaning of each "
             "deviation is in the `note` of its entry in `docs/api/<package>.json`.", "",
             "| Code | Symbols |", "|---|---:|"]
    text += [f"| `{code}` | {n} |" for code, n in sorted(codes.items(), key=lambda kv: (-kv[1], kv[0]))]
    text += ["", "Out of scope (Go compiler, runtime and tooling): " +
             ", ".join(f"`{r['go_package']}`" for r in rows if r["status"] == "out-of-scope") + "."]
    return json.dumps(data, indent=2) + "\n", "\n".join(text) + "\n"


def generate(check_only):
    surface = load_surface()
    mappings, errors = load_mappings(surface)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    codes = collections.Counter(
        part
        for package in surface["packages"]
        for entry in mappings.get(package, {}).get("symbols", {}).values()
        if "deviation" in entry
        for part in entry["deviation"].split("+"))
    coverage_json, coverage_md = render_coverage(surface, tally(surface, mappings), codes)
    outputs = {path: render_test(surface, mappings, key)[0] for key, _, path, _ in SURFACES}
    outputs.update({ROOT / "docs/coverage.json": coverage_json, ROOT / "docs/COVERAGE.md": coverage_md})
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if check_only:
        if stale:
            print("stale generated files (run python3 tools/api_parity.py): " +
                  ", ".join(str(p.relative_to(ROOT)) for p in stale), file=sys.stderr)
            return 1
        totals = json.loads(coverage_json)["totals"]
        print(json.dumps(totals))
        return 0
    for path, text in outputs.items():
        path.write_text(text)
    print(json.dumps(json.loads(coverage_json)["totals"]))
    return 0


def snake(name):
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def candidates(module, symbol):
    base = module if module.startswith(tuple(prefix for _, prefix, _, _ in SURFACES)) else f"{CRATE}{module}"
    name, kind = symbol["name"], symbol["kind"]
    if "." in name:
        owner, member = name.split(".", 1)
        return [{"rust": f"{base}::{owner}::{snake(member)}"}]
    if kind == "type":
        return [{"rust": f"{base}::{name}"}]
    if kind in ("const", "var"):
        return [{"rust": f"{base}::{snake(name).upper()}"}, {"rust": f"{base}::{snake(name)}"},
                {"rust": f"{base}::{name}"}]
    return [{"rust": f"{base}::{snake(name)}"}]


def compile_errors():
    """Run rustdoc for every surface; returns {surface key: failing line numbers}."""
    failing = {}
    for key, _, _, manifest in SURFACES:
        command = ["cargo", "rustdoc", "--offline", "--locked", "--lib"]
        if manifest:
            command += ["--manifest-path", manifest]
        run = subprocess.run(command + ["--", "--document-private-items", "-A", "rustdoc::private_intra_doc_links"],
                             cwd=ROOT, capture_output=True, text=True)
        if run.returncode == 0:
            continue
        lines = {int(m.group(1)) for m in re.finditer(r"src/api_surface\.rs:(\d+):", run.stderr)}
        if not lines:
            raise RuntimeError(run.stderr[-4000:])
        failing[key] = lines
    return failing


def bootstrap(pairs):
    surface = load_surface()
    for pair in pairs:
        package, module = pair.split("=", 1)
        if package not in surface["packages"]:
            raise SystemExit(f"{package} is not an in-scope package")
        path = mapping_path(package)
        data = json.loads(path.read_text()) if path.exists() else {"package": package, "symbols": {}}
        for symbol in surface["packages"][package]:
            if symbol["name"] in data["symbols"]:
                continue
            options = candidates(module, symbol)
            data["symbols"][symbol["name"]] = dict(options[0], auto=True, _options=options[1:])
        data["symbols"] = dict(sorted(data["symbols"].items()))
        path.write_text(json.dumps(data, indent=2) + "\n")
    # Prune guesses that do not compile, trying fallbacks before dropping.
    while True:
        mappings, errors = load_mappings(surface)
        if errors:
            raise SystemExit("\n".join(errors))
        origins = {}
        for key, _, path, _ in SURFACES:
            test, origins[key] = render_test(surface, mappings, key)
            path.write_text(test)
        failing = compile_errors()
        if not failing:
            break
        touched = collections.defaultdict(list)
        for key, lines in failing.items():
            for line in lines:
                if line in origins[key]:
                    touched[origins[key][line][0]].append(origins[key][line][1])
        if not touched:
            raise RuntimeError("compile errors outside mapped statements")
        for package, names in touched.items():
            path = mapping_path(package)
            data = json.loads(path.read_text())
            for name in names:
                entry = data["symbols"][name]
                if not entry.get("auto"):
                    raise SystemExit(f"reviewed mapping {package} {name} does not compile")
                rest = entry.get("_options", [])
                if rest:
                    data["symbols"][name] = dict(rest[0], auto=True, _options=rest[1:])
                else:
                    del data["symbols"][name]
            path.write_text(json.dumps(data, indent=2) + "\n")
    for path in API.glob("*.json"):
        if path == SURFACE:
            continue
        data = json.loads(path.read_text())
        for entry in data["symbols"].values():
            entry.pop("_options", None)
        path.write_text(json.dumps(data, indent=2) + "\n")
    return generate(False)


def main(argv):
    if argv[:1] == ["--surface"]:
        regenerate_surface()
        return 0
    if argv[:1] == ["--bootstrap"]:
        return bootstrap(argv[1:])
    if argv[:1] == ["--links"]:
        status = generate(False)
        failing = compile_errors()
        if failing:
            for key, lines in sorted(failing.items()):
                print(f"unresolved mappings in the {key} api_surface.rs at lines {sorted(lines)}", file=sys.stderr)
            return 1
        return status
    if argv[:1] == ["--check"]:
        status = generate(True)
        if status == 0 and compile_errors():
            print("unresolved mappings in an api_surface.rs; run python3 tools/api_parity.py --links",
                  file=sys.stderr)
            return 1
        return status
    return generate(False)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
