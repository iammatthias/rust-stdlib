// Generates tests/fixtures/asn1_golden.rs from the local Go toolchain's
// encoding/asn1 tests. Nothing is hand-typed: the tables are parsed with
// go/parser and evaluated with go/constant; big-integer expectations are
// converted to two's-complement bytes with math/big.
//
// Usage, from the repository root:
//
//	go run tools/asn1_vectors.go
//	rustfmt --edition 2021 tests/fixtures/asn1_golden.rs
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"math/big"
	"os"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
)

var consts = map[string]constant.Value{
	"math.MaxInt32":        constant.MakeInt64(1<<31 - 1),
	"TagInteger":           constant.MakeInt64(2),
	"ClassContextSpecific": constant.MakeInt64(2),
	"ClassApplication":     constant.MakeInt64(1),
	"ClassPrivate":         constant.MakeInt64(3),
}

func eval(e ast.Expr) constant.Value {
	switch e := e.(type) {
	case *ast.BasicLit:
		return constant.MakeFromLiteral(e.Value, e.Kind, 0)
	case *ast.ParenExpr:
		return eval(e.X)
	case *ast.UnaryExpr:
		return constant.UnaryOp(e.Op, eval(e.X), 0)
	case *ast.BinaryExpr:
		return constant.BinaryOp(eval(e.X), e.Op, eval(e.Y))
	case *ast.Ident:
		if v, ok := consts[e.Name]; ok {
			return v
		}
	case *ast.SelectorExpr:
		if x, ok := e.X.(*ast.Ident); ok {
			if v, ok := consts[x.Name+"."+e.Sel.Name]; ok {
				return v
			}
		}
	}
	panic(fmt.Sprintf("cannot evaluate %T", e))
}

func evalInt(e ast.Expr) int64 {
	v, ok := constant.Int64Val(constant.ToInt(eval(e)))
	if !ok {
		panic("integer out of range")
	}
	return v
}

func evalString(e ast.Expr) string {
	return constant.StringVal(eval(e))
}

func evalBool(e ast.Expr) bool {
	return e.(*ast.Ident).Name == "true"
}

func byteSlice(e ast.Expr) []byte {
	switch e := e.(type) {
	case *ast.CompositeLit:
		out := make([]byte, 0, len(e.Elts))
		for _, el := range e.Elts {
			out = append(out, byte(evalInt(el)))
		}
		return out
	case *ast.CallExpr: // []byte("...")
		return []byte(evalString(e.Args[0]))
	}
	panic(fmt.Sprintf("not a byte slice: %T", e))
}

func rustBytes(b []byte) string {
	parts := make([]string, len(b))
	for i, v := range b {
		parts[i] = fmt.Sprintf("0x%02x", v)
	}
	return "&[" + strings.Join(parts, ", ") + "]"
}

// timeValue evaluates time.Date(...) or time.Time{} to Rust tuple text.
func timeValue(e ast.Expr) string {
	call, ok := e.(*ast.CallExpr)
	if !ok {
		return "(0, 0, 0, 0, 0, 0, 0, 0)"
	}
	var f [7]int64
	for i := 0; i < 7; i++ {
		f[i] = evalInt(call.Args[i])
	}
	offset := int64(0)
	if zone, ok := call.Args[7].(*ast.CallExpr); ok { // time.FixedZone("", n)
		offset = evalInt(zone.Args[1])
	}
	return fmt.Sprintf("(%d, %d, %d, %d, %d, %d, %d, %d)", f[0], f[1], f[2], f[3], f[4], f[5], f[6], offset)
}

func table(file *ast.File, name string) []*ast.CompositeLit {
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.VAR {
			continue
		}
		for _, spec := range gen.Specs {
			vs := spec.(*ast.ValueSpec)
			if vs.Names[0].Name != name {
				continue
			}
			var rows []*ast.CompositeLit
			for _, el := range vs.Values[0].(*ast.CompositeLit).Elts {
				rows = append(rows, el.(*ast.CompositeLit))
			}
			return rows
		}
	}
	panic("table not found: " + name)
}

func twosComplement(base10 string) []byte {
	n, ok := new(big.Int).SetString(base10, 10)
	if !ok {
		panic("bad integer " + base10)
	}
	if n.Sign() >= 0 {
		b := n.Bytes()
		if len(b) == 0 || b[0]&0x80 != 0 {
			b = append([]byte{0}, b...)
		}
		return b
	}
	m := new(big.Int).Neg(n)
	m.Sub(m, big.NewInt(1))
	b := m.Bytes()
	for i := range b {
		b[i] ^= 0xff
	}
	if len(b) == 0 || b[0]&0x80 == 0 {
		b = append([]byte{0xff}, b...)
	}
	return b
}

func main() {
	src := filepath.Join(runtime.GOROOT(), "src", "encoding", "asn1", "asn1_test.go")
	file, err := parser.ParseFile(token.NewFileSet(), src, nil, 0)
	if err != nil {
		panic(err)
	}
	var out bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&out, format, args...) }
	w("// Generated by tools/asn1_vectors.go from Go's encoding/asn1/asn1_test.go. Do not edit.\n\n")
	w("#[allow(dead_code)]\npub type Time = (u16, u8, u8, u8, u8, u8, u32, i32);\n")
	w("/// (class, tag, length, compound)\npub type TagAndLength = (u8, u32, usize, bool);\n\n")

	w("pub const BOOL: &[(&[u8], bool, bool)] = &[\n")
	for _, r := range table(file, "boolTestData") {
		w("(%s, %v, %v),\n", rustBytes(byteSlice(r.Elts[0])), evalBool(r.Elts[1]), evalBool(r.Elts[2]))
	}
	w("];\n\npub const INT64: &[(&[u8], bool, i64)] = &[\n")
	for _, r := range table(file, "int64TestData") {
		w("(%s, %v, %d),\n", rustBytes(byteSlice(r.Elts[0])), evalBool(r.Elts[1]), evalInt(r.Elts[2]))
	}
	w("];\n\npub const INT32: &[(&[u8], bool, i32)] = &[\n")
	for _, r := range table(file, "int32TestData") {
		w("(%s, %v, %d),\n", rustBytes(byteSlice(r.Elts[0])), evalBool(r.Elts[1]), evalInt(r.Elts[2]))
	}
	w("];\n\n/// (input, ok, two's-complement value)\npub const BIG_INT: &[(&[u8], bool, &[u8])] = &[\n")
	for _, r := range table(file, "bigIntTests") {
		ok := evalBool(r.Elts[1])
		value := []byte{}
		if ok {
			value = twosComplement(evalString(r.Elts[2]))
		}
		w("(%s, %v, %s),\n", rustBytes(byteSlice(r.Elts[0])), ok, rustBytes(value))
	}
	w("];\n\npub const BIT_STRING: &[(&[u8], bool, &[u8], usize)] = &[\n")
	for _, r := range table(file, "bitStringTestData") {
		w("(%s, %v, %s, %d),\n", rustBytes(byteSlice(r.Elts[0])), evalBool(r.Elts[1]), rustBytes(byteSlice(r.Elts[2])), evalInt(r.Elts[3]))
	}
	w("];\n\npub const BIT_STRING_RIGHT_ALIGN: &[(&[u8], usize, &[u8])] = &[\n")
	for _, r := range table(file, "bitStringRightAlignTests") {
		w("(%s, %d, %s),\n", rustBytes(byteSlice(r.Elts[0])), evalInt(r.Elts[1]), rustBytes(byteSlice(r.Elts[2])))
	}
	w("];\n\npub const OBJECT_IDENTIFIER: &[(&[u8], bool, &[i64])] = &[\n")
	for _, r := range table(file, "objectIdentifierTestData") {
		var arcs []string
		for _, el := range r.Elts[2].(*ast.CompositeLit).Elts {
			arcs = append(arcs, strconv.FormatInt(evalInt(el), 10))
		}
		w("(%s, %v, &[%s]),\n", rustBytes(byteSlice(r.Elts[0])), evalBool(r.Elts[1]), strings.Join(arcs, ", "))
	}
	for _, t := range []struct{ rust, goName string }{{"UTC_TIME", "utcTestData"}, {"GENERALIZED_TIME", "generalizedTimeTestData"}} {
		w("];\n\npub const %s: &[(&str, bool, Time)] = &[\n", t.rust)
		for _, r := range table(file, t.goName) {
			w("(%q, %v, %s),\n", evalString(r.Elts[0]), evalBool(r.Elts[1]), timeValue(r.Elts[2]))
		}
	}
	w("];\n\npub const TAG_AND_LENGTH: &[(&[u8], bool, TagAndLength)] = &[\n")
	for _, r := range table(file, "tagAndLengthData") {
		var f [4]int64
		var compound bool
		lit := r.Elts[2].(*ast.CompositeLit)
		for i, el := range lit.Elts {
			idx := i
			if kv, ok := el.(*ast.KeyValueExpr); ok {
				idx = map[string]int{"class": 0, "tag": 1, "length": 2, "isCompound": 3}[kv.Key.(*ast.Ident).Name]
				el = kv.Value
			}
			if idx == 3 {
				compound = evalBool(el)
			} else {
				f[idx] = evalInt(el)
			}
		}
		w("(%s, %v, (%d, %d, %d, %v)),\n", rustBytes(byteSlice(r.Elts[0])), evalBool(r.Elts[1]), f[0], f[1], f[2], compound)
	}
	w("];\n\n/// (name, decoded, encoded hex, invalid)\npub const BMP_STRING: &[(&str, &str, &str, bool)] = &[\n")
	for _, r := range table(file, "bmpStringTests") {
		w("(%q, %q, %q, %v),\n", evalString(r.Elts[0]), evalString(r.Elts[1]), evalString(r.Elts[2]), evalBool(r.Elts[3]))
	}
	w("];\n")
	for _, c := range []struct{ rust, goName string }{{"SELF_SIGNED_CERT", "derEncodedSelfSignedCertBytes"}, {"PAYPAL_NUL_CERT", "derEncodedPaypalNULCertBytes"}} {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.VAR {
				continue
			}
			for _, spec := range gen.Specs {
				vs := spec.(*ast.ValueSpec)
				if vs.Names[0].Name == c.goName {
					w("\npub const %s: &[u8] = %s;\n", c.rust, rustBytes(byteSlice(vs.Values[0])))
				}
			}
		}
	}
	if err := os.WriteFile("tests/fixtures/asn1_golden.rs", out.Bytes(), 0o644); err != nil {
		panic(err)
	}
}
