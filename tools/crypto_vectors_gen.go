// Extracts the known-answer tables from Go's crypto test files into the
// tab-separated fixtures in crates/crypto/tests/fixtures.
//
// Usage: go run tools/crypto_vectors_gen.go OUTDIR
//
// Each fixture line is one table row. Fields are separated by tabs and typed:
// s:HEX for strings and byte slices, i:N for integers, f:NAME for a hash
// constructor such as sha256.New. The tables are Go's (BSD-licensed, see NOTICE).
package main

import (
	"encoding/hex"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
)

type table struct {
	file, variable, out string
}

var tables = []table{
	{"crypto/md5/md5_test.go", "golden", "md5.tsv"},
	{"crypto/sha1/sha1_test.go", "golden", "sha1.tsv"},
	{"crypto/sha256/sha256_test.go", "golden", "sha256.tsv"},
	{"crypto/sha256/sha256_test.go", "golden224", "sha224.tsv"},
	{"crypto/sha512/sha512_test.go", "golden224", "sha512_224.tsv"},
	{"crypto/sha512/sha512_test.go", "golden256", "sha512_256.tsv"},
	{"crypto/sha512/sha512_test.go", "golden384", "sha384.tsv"},
	{"crypto/sha512/sha512_test.go", "golden512", "sha512.tsv"},
	{"crypto/hmac/hmac_test.go", "hmacTests", "hmac.tsv"},
	{"crypto/hkdf/hkdf_test.go", "hkdfTests", "hkdf.tsv"},
	{"crypto/pbkdf2/pbkdf2_test.go", "sha1TestVectors", "pbkdf2_sha1.tsv"},
	{"crypto/pbkdf2/pbkdf2_test.go", "sha256TestVectors", "pbkdf2_sha256.tsv"},
}

func field(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.BasicLit:
		switch e.Kind {
		case token.STRING:
			s, err := strconv.Unquote(e.Value)
			must(err)
			return "s:" + hex.EncodeToString([]byte(s))
		case token.INT:
			return "i:" + e.Value
		}
	case *ast.CompositeLit: // []byte{0x01, ...}
		var b []byte
		for _, element := range e.Elts {
			n, err := strconv.ParseUint(element.(*ast.BasicLit).Value, 0, 8)
			must(err)
			b = append(b, byte(n))
		}
		return "s:" + hex.EncodeToString(b)
	case *ast.Ident: // nil byte slices act as empty ones
		if e.Name == "nil" {
			return "s:"
		}
	case *ast.BinaryExpr: // "..." + "..."
		if e.Op == token.ADD {
			return field(e.X) + strings.TrimPrefix(field(e.Y), "s:")
		}
	case *ast.CallExpr: // []byte("...")
		return field(e.Args[0])
	case *ast.SelectorExpr:
		return "f:" + e.X.(*ast.Ident).Name + "." + e.Sel.Name
	}
	panic(fmt.Sprintf("unsupported expression %T: %v", expr, expr))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func main() {
	out := os.Args[1]
	root := filepath.Join(runtime.GOROOT(), "src")
	for _, t := range tables {
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, filepath.Join(root, t.file), nil, 0)
		must(err)
		var rows []string
		ast.Inspect(file, func(n ast.Node) bool {
			spec, ok := n.(*ast.ValueSpec)
			if !ok || spec.Names[0].Name != t.variable {
				return true
			}
			for _, row := range spec.Values[0].(*ast.CompositeLit).Elts {
				var fields []string
				for _, element := range row.(*ast.CompositeLit).Elts {
					fields = append(fields, field(element))
				}
				rows = append(rows, strings.Join(fields, "\t"))
			}
			return false
		})
		header := fmt.Sprintf("# From Go %s %s (BSD-licensed, see NOTICE); generated by tools/crypto_vectors_gen.go\n", t.file, t.variable)
		must(os.WriteFile(filepath.Join(out, t.out), []byte(header+strings.Join(rows, "\n")+"\n"), 0o644))
		fmt.Printf("%s: %d rows\n", t.out, len(rows))
	}
}
