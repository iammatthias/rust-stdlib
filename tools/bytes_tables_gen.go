// bytes_tables_gen writes src/text/size_classes.rs: Go's malloc size classes, which
// rust_stdlib::bytes uses to reproduce Buffer capacities. Run from the
// repository root:
//
//	go run tools/bytes_tables_gen.go > src/text/size_classes.rs
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

func main() {
	src, err := os.ReadFile(filepath.Join(runtime.GOROOT(), "src/internal/runtime/gc/sizeclasses.go"))
	if err != nil {
		panic(err)
	}
	m := regexp.MustCompile(`SizeClassToSize = \[NumSizeClasses\]uint16\{([^}]*)\}`).FindSubmatch(src)
	fmt.Printf("//! Generated by tools/bytes_tables_gen.go from Go %s; do not edit.\n\n", runtime.Version())
	fmt.Printf("/// Go's malloc size classes (`gc.SizeClassToSize`), used to reproduce `cap`.\npub(super) const BYTES_SIZE_CLASSES: &[usize] = &[%s];\n", strings.TrimSpace(string(m[1])))
}
