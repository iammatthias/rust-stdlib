#!/usr/bin/env python3
"""Writes the Go and Rust type definitions of the gob differential from
tools/gob_spec.py, or with --check verifies the committed files are current."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gob_spec as spec  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
GO_OUT = ROOT / "tools/gob_types_gen.go"
RUST_OUT = ROOT / "tools/derive-check/gob_types_gen.rs"


def all_keys():
    structs, twins = spec.build()
    ifaces = spec.registered(structs)
    tops = spec.tops(structs)
    table = {}
    lits = spec.Lits(structs, ifaces, 0)
    for k in ifaces:
        table.setdefault(k, lits.type_of_key(k))
    for k, t in tops.items():
        table.setdefault(k, t)
    for s in twins:
        table[s.name] = ("s", s.name)
    return structs, twins, ifaces, table


def go_source():
    structs, twins, ifaces, table = all_keys()
    out = ["// Code generated by tools/gob_gen.py; DO NOT EDIT.", "", "package main", "",
           'import "reflect"', ""]
    for s in structs + twins:
        out.append("type %s struct {" % s.name)
        for name, t, exported, embedded in s.fields:
            out.append("\t%s" % name if embedded else "\t%s %s" % (name, spec.go(t)))
        out.append("}")
        out.append("")
    out.append("func genTypes() (map[string]reflect.Type, []string) {")
    out.append("\ttable := map[string]reflect.Type{}")
    for k, t in table.items():
        out.append('\ttable[%s] = reflect.TypeOf((*%s)(nil)).Elem()' % (go_str(k), spec.go(t)))
    out.append("\treturn table, []string{%s}" % ", ".join(go_str(k) for k in ifaces))
    out.append("}")
    return "\n".join(out) + "\n"


def go_str(s):
    return '"%s"' % s


def rust_source():
    structs, twins, ifaces, table = all_keys()
    out = ["// Code generated by tools/gob_gen.py; DO NOT EDIT.", ""]
    for s in structs + twins:
        out.append("#[derive(Reflect)]")
        out.append('#[reflect(pkg = "main")]')
        out.append("pub struct %s {" % s.name)
        for name, t, exported, embedded in s.fields:
            if embedded:
                out.append("    #[reflect(embed)]")
            vis = "pub " if exported else ""
            out.append("    %s%s: %s," % (vis, name, spec.rust(t)))
        out.append("}")
        out.append("")
    out.append("fn gen_types() -> (Vec<(&'static str, Type)>, Vec<&'static str>) {")
    out.append("    let table: Vec<(&'static str, Type)> = vec![")
    for k, t in table.items():
        out.append('        ("%s", reflect::type_for::<%s>()),' % (k, spec.rust(t)))
    out.append("    ];")
    out.append("    (table, vec![%s])" % ", ".join('"%s"' % k for k in ifaces))
    out.append("}")
    return "\n".join(out) + "\n"


def main_check():
    ok = (GO_OUT.exists() and GO_OUT.read_text() == go_source()
          and RUST_OUT.exists() and RUST_OUT.read_text() == rust_source())
    if not ok:
        raise SystemExit("gob type files are stale: run python3 tools/gob_gen.py")


def main():
    if "--check" in sys.argv:
        main_check()
        return
    GO_OUT.write_text(go_source())
    RUST_OUT.write_text(rust_source())


if __name__ == "__main__":
    main()
