// Generates src/math/rand/tables.rs and tests/fixtures/rand_golden.rs from the
// local Go toolchain's math/rand sources and tests. Nothing is hand-typed: the
// tables and golden vectors are parsed with go/parser and evaluated with
// go/constant, and every float is emitted as its exact IEEE-754 bit pattern.
//
// Usage, from the repository root:
//
//	go run tools/rand_tables.go
//	rustfmt --edition 2021 src/math/rand/tables.rs tests/fixtures/rand_golden.rs
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"math"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

var goroot = runtime.GOROOT()

type parsed struct {
	fset     *token.FileSet
	file     *ast.File
	comments map[int]string
}

func parse(rel string) *parsed {
	fset := token.NewFileSet()
	path := filepath.Join(goroot, "src", rel)
	file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		panic(err)
	}
	comments := map[int]string{}
	for _, group := range file.Comments {
		for _, c := range group.List {
			comments[fset.Position(c.Pos()).Line] = strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		}
	}
	return &parsed{fset, file, comments}
}

// lit returns the composite literal assigned to the package-level var name.
func (p *parsed) lit(name string) *ast.CompositeLit {
	for _, decl := range p.file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.VAR {
			continue
		}
		for _, spec := range gen.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, ident := range vs.Names {
				if ident.Name != name {
					continue
				}
				switch v := vs.Values[i].(type) {
				case *ast.CompositeLit:
					return v
				case *ast.CallExpr: // [32]byte([]byte("..."))
					return &ast.CompositeLit{Elts: v.Args}
				}
			}
		}
	}
	panic("missing var " + name)
}

func (p *parsed) value(name string) constant.Value {
	for _, decl := range p.file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.VAR {
			continue
		}
		for _, spec := range gen.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, ident := range vs.Names {
				if ident.Name == name && i < len(vs.Values) {
					return eval(vs.Values[i])
				}
			}
		}
	}
	panic("missing var " + name)
}

// eval evaluates an untyped constant expression (literals, unary minus,
// type conversions, string calls such as hex.DecodeString("...")).
func eval(e ast.Expr) constant.Value { return evalEnv(e, nil) }

func evalEnv(e ast.Expr, env map[string]constant.Value) constant.Value {
	eval := func(e ast.Expr) constant.Value { return evalEnv(e, env) }
	switch v := e.(type) {
	case *ast.Ident:
		if x, ok := env[v.Name]; ok {
			return x
		}
	case *ast.BinaryExpr:
		if v.Op == token.SHL {
			n, _ := constant.Uint64Val(eval(v.Y))
			return constant.Shift(eval(v.X), token.SHL, uint(n))
		}
		x, y := eval(v.X), eval(v.Y)
		if v.Op == token.QUO {
			x = constant.ToFloat(x)
		}
		return constant.BinaryOp(x, v.Op, y)
	case *ast.SelectorExpr: // math.Sqrt2 and friends
		if x, ok := env[v.Sel.Name]; ok {
			return x
		}
	case *ast.BasicLit:
		return constant.MakeFromLiteral(v.Value, v.Kind, 0)
	case *ast.UnaryExpr:
		return constant.UnaryOp(v.Op, eval(v.X), 0)
	case *ast.ParenExpr:
		return eval(v.X)
	case *ast.CallExpr:
		if len(v.Args) == 1 {
			return eval(v.Args[0])
		}
	}
	panic(fmt.Sprintf("unsupported constant expression %T %v", e, e))
}

func i64(e ast.Expr) int64 {
	x, exact := constant.Int64Val(eval(e))
	if !exact {
		panic("inexact int64")
	}
	return x
}

func u64(e ast.Expr) uint64 {
	x, exact := constant.Uint64Val(eval(e))
	if !exact {
		panic("inexact uint64")
	}
	return x
}

// f32bits rounds the exact constant directly to float32, as the Go compiler does.
func f32bits(e ast.Expr) uint32 {
	x, _ := constant.Float32Val(eval(e))
	return math.Float32bits(x)
}

func f64bits(e ast.Expr) uint64 {
	x, _ := constant.Float64Val(eval(e))
	return math.Float64bits(x)
}

func str(e ast.Expr) string {
	return constant.StringVal(eval(e))
}

func rustBytes(b []byte) string {
	var out strings.Builder
	out.WriteString("b\"")
	for _, c := range b {
		fmt.Fprintf(&out, "\\x%02x", c)
	}
	out.WriteString("\"")
	return out.String()
}

const header = `// Code generated by tools/rand_tables.go from the Go %s sources; DO NOT EDIT.
//
// Copyright 2009 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the NOTICE file.
`

func tables() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, header, runtime.Version())
	b.WriteString("//\n// Ported from $GOROOT/src/math/rand/rng.go (rngCooked) and\n// $GOROOT/src/math/rand/v2/{normal,exp}.go (ziggurat tables, identical in v1).\n\n")
	b.WriteString("// Float constants from $GOROOT/src/math/{const,log,exp}.go and the ziggurat\n// constants rn/re; compile-time folds such as 1.0/rn are evaluated exactly.\n")
	b.Write(floatConsts())
	rng := parse("math/rand/rng.go").lit("rngCooked")
	fmt.Fprintf(&b, "/// Go's `rngCooked`: the lagged Fibonacci state after 7.8e12 steps.\npub(crate) const RNG_COOKED: [i64; %d] = [\n", len(rng.Elts))
	for _, e := range rng.Elts {
		fmt.Fprintf(&b, "%d,\n", i64(e))
	}
	b.WriteString("];\n\n")
	for _, spec := range []struct{ file, name, rust, kind string }{
		{"math/rand/v2/normal.go", "kn", "KN", "u32"},
		{"math/rand/v2/normal.go", "wn", "WN", "f32"},
		{"math/rand/v2/normal.go", "fn", "FN", "f32"},
		{"math/rand/v2/exp.go", "ke", "KE", "u32"},
		{"math/rand/v2/exp.go", "we", "WE", "f32"},
		{"math/rand/v2/exp.go", "fe", "FE", "f32"},
	} {
		l := parse(spec.file).lit(spec.name)
		fmt.Fprintf(&b, "/// Go's ziggurat table `%s`.\npub(crate) const %s: [%s; %d] = [\n", spec.name, spec.rust, spec.kind, len(l.Elts))
		for _, e := range l.Elts {
			if spec.kind == "u32" {
				fmt.Fprintf(&b, "%#x,\n", u64(e))
			} else {
				fmt.Fprintf(&b, "f32::from_bits(0x%08x),\n", f32bits(e))
			}
		}
		b.WriteString("];\n\n")
	}
	return b.Bytes()
}

// consts collects const declarations at package level and inside the named
// functions of a file, evaluated exactly with go/constant as the compiler does.
func consts(rel string, env map[string]constant.Value, prefix map[string]string, out map[string]constant.Value) {
	p := parse(rel)
	collect := func(decl *ast.GenDecl, owner string) {
		if decl.Tok != token.CONST {
			return
		}
		for _, spec := range decl.Specs {
			vs := spec.(*ast.ValueSpec)
			for i, ident := range vs.Names {
				if i >= len(vs.Values) {
					continue
				}
				x, ok := tryEval(vs.Values[i], env)
				if !ok {
					continue // e.g. math's typed integer limits; unused here
				}
				env[ident.Name] = x
				if name, ok := prefix[owner]; ok {
					out[name+strings.ToUpper(ident.Name)] = x
				}
			}
		}
	}
	for _, decl := range p.file.Decls {
		switch d := decl.(type) {
		case *ast.GenDecl:
			collect(d, "")
		case *ast.FuncDecl:
			ast.Inspect(d.Body, func(n ast.Node) bool {
				if g, ok := n.(*ast.GenDecl); ok {
					collect(g, d.Name.Name)
				}
				return true
			})
		}
	}
}

func tryEval(e ast.Expr, env map[string]constant.Value) (x constant.Value, ok bool) {
	defer func() {
		if recover() != nil {
			ok = false
		}
	}()
	return evalEnv(e, env), true
}

func floatConsts() []byte {
	out := map[string]constant.Value{}
	env := map[string]constant.Value{}
	consts("math/const.go", env, nil, out)
	consts("math/log.go", map[string]constant.Value{"Sqrt2": env["Sqrt2"]}, map[string]string{"log": "LOG_"}, out)
	consts("math/exp.go", map[string]constant.Value{}, map[string]string{"exp": "EXP_", "expmulti": "EXPMULTI_"}, out)
	consts("math/rand/v2/normal.go", map[string]constant.Value{}, map[string]string{"": ""}, out)
	consts("math/rand/v2/exp.go", map[string]constant.Value{}, map[string]string{"": ""}, out)
	// Expressions that Go folds at compile time inside the algorithms.
	out["LOG_SQRT2_HALF"] = constant.BinaryOp(constant.ToFloat(env["Sqrt2"]), token.QUO, constant.MakeInt64(2))
	out["RN_INV"] = constant.BinaryOp(constant.MakeFloat64(1), token.QUO, out["RN"])
	var names []string
	for name := range out {
		names = append(names, name)
	}
	sort.Strings(names)
	var b bytes.Buffer
	for _, name := range names {
		x, _ := constant.Float64Val(constant.ToFloat(out[name]))
		fmt.Fprintf(&b, "/// `%s` rounded once to float64 (%s).\npub(crate) const %s: f64 = f64::from_bits(0x%016x);\n", name, strconv.FormatFloat(x, 'g', -1, 64), name, math.Float64bits(x))
	}
	b.WriteString("\n")
	return b.Bytes()
}

// golden converts a regressGolden table into Rust (method, argument, value) rows.
func golden(p *parsed, name string) string {
	var b strings.Builder
	l := p.lit(name)
	fmt.Fprintf(&b, "&[\n")
	for _, e := range l.Elts {
		line := p.fset.Position(e.End()).Line
		comment, ok := p.comments[line]
		if !ok {
			panic("golden element without method comment")
		}
		method, arg, _ := strings.Cut(strings.TrimSuffix(comment, ")"), "(")
		argValue := "0"
		if strings.HasPrefix(arg, "[") { // Read([0 0 0]): the argument is the buffer length
			argValue = fmt.Sprint(len(strings.Fields(strings.Trim(arg, "[]"))))
		} else if arg != "" {
			argValue = arg
		}
		var value string
		switch v := e.(type) {
		case *ast.CallExpr:
			switch fmt.Sprint(v.Fun) {
			case "float64":
				value = fmt.Sprintf("G::F64(0x%016x)", f64bits(v.Args[0]))
			case "float32":
				value = fmt.Sprintf("G::F32(0x%08x)", f32bits(v.Args[0]))
			case "int64", "int32":
				value = fmt.Sprintf("G::I64(%d)", i64(v.Args[0]))
			case "uint64", "uint32":
				value = fmt.Sprintf("G::U64(%d)", u64(v.Args[0]))
			default:
				panic("unexpected golden type " + fmt.Sprint(v.Fun))
			}
		case *ast.CompositeLit:
			var parts []string
			for _, x := range v.Elts {
				parts = append(parts, fmt.Sprint(u64(x)))
			}
			kind := "Ints"
			if fmt.Sprint(v.Type.(*ast.ArrayType).Elt) == "byte" {
				kind = "Bytes"
			}
			value = fmt.Sprintf("G::%s(&[%s])", kind, strings.Join(parts, ", "))
		default:
			panic(fmt.Sprintf("unexpected golden element %T", e))
		}
		fmt.Fprintf(&b, "(%q, %s, %s),\n", method, argValue, value)
	}
	b.WriteString("]")
	return b.String()
}

func fixtures() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, header, runtime.Version())
	b.WriteString("//\n// Golden vectors from $GOROOT/src/math/rand/regress_test.go,\n// $GOROOT/src/math/rand/v2/{regress,pcg,chacha8}_test.go. Included by tests/rand.rs.\n\n")
	v1 := parse("math/rand/regress_test.go")
	fmt.Fprintf(&b, "/// math/rand regressGolden; one `Rand` re-seeded with 0 per method.\nconst V1_REGRESS: &[(&str, u64, G)] = %s;\n\n", golden(v1, "regressGolden"))
	v2 := parse("math/rand/v2/regress_test.go")
	fmt.Fprintf(&b, "/// math/rand/v2 regressGolden; a fresh `New(NewPCG(1, 2))` per method.\nconst V2_REGRESS: &[(&str, u64, G)] = %s;\n\n", golden(v2, "regressGolden"))

	pcg := parse("math/rand/v2/pcg_test.go")
	var want []string
	for _, fn := range pcg.file.Decls {
		f, ok := fn.(*ast.FuncDecl)
		if !ok || f.Name.Name != "TestPCG" {
			continue
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if cl, ok := n.(*ast.CompositeLit); ok {
				for _, e := range cl.Elts {
					want = append(want, fmt.Sprintf("%#x", u64(e)))
				}
				return false
			}
			return true
		})
	}
	fmt.Fprintf(&b, "/// TestPCG: NewPCG(1, 2) outputs.\nconst PCG_OUTPUT: [u64; %d] = [%s];\n\n", len(want), strings.Join(want, ", "))

	cc := parse("math/rand/v2/chacha8_test.go")
	var seed []byte
	for _, e := range cc.lit("chacha8seed").Elts {
		seed = append(seed, str(e)...)
	}
	fmt.Fprintf(&b, "/// chacha8seed.\nconst CHACHA8_SEED: [u8; 32] = *%s;\n\n", rustBytes(seed))
	fmt.Fprintf(&b, "/// chacha8outlen.\nconst CHACHA8_OUTLEN: usize = %s;\n\n", cc.value("chacha8outlen").ExactString())
	var out []string
	for _, e := range cc.lit("chacha8output").Elts {
		out = append(out, fmt.Sprintf("0x%016x", u64(e)))
	}
	fmt.Fprintf(&b, "/// chacha8output.\nconst CHACHA8_OUTPUT: [u64; %d] = [%s];\n\n", len(out), strings.Join(out, ", "))
	for _, spec := range []struct{ name, rust string }{{"chacha8marshal", "CHACHA8_MARSHAL"}, {"chacha8marshalread", "CHACHA8_MARSHAL_READ"}} {
		l := cc.lit(spec.name)
		fmt.Fprintf(&b, "/// %s.\nconst %s: [&[u8]; %d] = [\n", spec.name, spec.rust, len(l.Elts))
		for _, e := range l.Elts {
			fmt.Fprintf(&b, "%s,\n", rustBytes([]byte(str(e))))
		}
		b.WriteString("];\n\n")
	}
	return b.Bytes()
}

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	if err := os.WriteFile(filepath.Join(root, "src/math/rand/tables.rs"), tables(), 0o644); err != nil {
		panic(err)
	}
	if err := os.WriteFile(filepath.Join(root, "tests/fixtures/rand_golden.rs"), fixtures(), 0o644); err != nil {
		panic(err)
	}
}
