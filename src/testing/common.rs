/// The panic payload that [`TB::fail_now`], [`TB::fatal`], [`TB::skip_now`]
/// and friends unwind with: Go's `runtime.Goexit`. The test runner recognises
/// it with [`is_goexit`]; it is raised with `resume_unwind`, so the panic hook
/// does not run and nothing is printed to stderr.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Goexit;

impl Display for Goexit {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("test executed runtime.Goexit")
    }
}

/// Reports whether a caught panic payload is the [`Goexit`] marker used by
/// `fail_now`, `fatal` and `skip_now`.
pub fn is_goexit(payload: &(dyn Any + Send)) -> bool {
    payload.is::<Goexit>()
}

pub(crate) fn goexit() -> ! {
    panic::resume_unwind(Box::new(Goexit))
}

/// Renders a panic payload the way Go prints `panic(v)` values.
pub(crate) fn panic_message(payload: &(dyn Any + Send)) -> String {
    if let Some(s) = payload.downcast_ref::<&'static str>() {
        (*s).to_string()
    } else if let Some(s) = payload.downcast_ref::<String>() {
        s.clone()
    } else if payload.is::<Goexit>() {
        Goexit.to_string()
    } else {
        "(non-string panic payload)".to_string()
    }
}

/// Where a test run writes its report: Go's `os.Stdout` for the test binary.
type SinkFn = Box<dyn FnMut(&str) + Send>;

pub struct Sink(Mutex<SinkFn>);

impl Sink {
    /// A sink calling `f` for every chunk of output.
    pub fn from_fn(f: impl FnMut(&str) + Send + 'static) -> Arc<Sink> {
        Arc::new(Sink(Mutex::new(Box::new(f))))
    }

    /// The process standard output, through `print!` so the Rust test harness
    /// captures it.
    pub fn stdout() -> Arc<Sink> {
        Sink::from_fn(|s| {
            print!("{s}");
        })
    }

    /// A sink that drops everything (Go's `io.Discard`).
    pub fn discard() -> Arc<Sink> {
        Sink::from_fn(|_| {})
    }

    /// A sink collecting into the returned shared string.
    pub fn buffer() -> (Arc<Sink>, Arc<Mutex<String>>) {
        let buf = Arc::new(Mutex::new(String::new()));
        let b = buf.clone();
        (Sink::from_fn(move |s| b.lock().unwrap().push_str(s)), buf)
    }

    pub(crate) fn write(&self, s: &str) {
        (self.0.lock().unwrap())(s);
    }
}

/// Go's `chattyPrinter`: verbose (`-test.v`) progress output.
pub(crate) struct Chatty {
    pub(crate) sink: Arc<Sink>,
    last_name: Mutex<String>,
}

impl Chatty {
    pub(crate) fn new(sink: Arc<Sink>) -> Arc<Chatty> {
        Arc::new(Chatty {
            sink,
            last_name: Mutex::new(String::new()),
        })
    }

    /// Prints a message about the named test; `text` includes the name.
    pub(crate) fn updatef(&self, test_name: &str, text: &str) {
        let mut last = self.last_name.lock().unwrap();
        *last = test_name.to_string();
        self.sink.write(text);
    }

    /// Prints a message generated by the named test that need not mention it.
    pub(crate) fn printf(&self, test_name: &str, text: &str) {
        let mut last = self.last_name.lock().unwrap();
        if last.is_empty() {
            *last = test_name.to_string();
        } else if *last != test_name {
            self.sink.write(&format!("=== NAME  {test_name}\n"));
            *last = test_name.to_string();
        }
        self.sink.write(text);
    }
}

#[derive(Default)]
struct Par {
    running: usize,
    waiting: usize,
    grants: usize,
}

/// Go's `testState`: everything common to the tests of one run.
pub(crate) struct TestState {
    pub(crate) matcher: Matcher,
    pub(crate) deadline: Option<Instant>,
    pub(crate) max_parallel: usize,
    pub(crate) failfast: bool,
    pub(crate) fullpath: bool,
    pub(crate) num_failed: std::sync::atomic::AtomicUsize,
    par: Mutex<Par>,
    cv: Condvar,
}

impl TestState {
    pub(crate) fn new(max_parallel: usize, matcher: Matcher) -> TestState {
        TestState {
            matcher,
            deadline: None,
            max_parallel: max_parallel.max(1),
            failfast: false,
            fullpath: false,
            num_failed: Default::default(),
            // The main (sequential) test holds one slot.
            par: Mutex::new(Par {
                running: 1,
                ..Par::default()
            }),
            cv: Condvar::new(),
        }
    }

    pub(crate) fn should_fail_fast(&self) -> bool {
        self.failfast && self.num_failed.load(Ordering::SeqCst) > 0
    }

    pub(crate) fn wait_parallel(&self) {
        let mut p = self.par.lock().unwrap();
        if p.running < self.max_parallel {
            p.running += 1;
            return;
        }
        p.waiting += 1;
        while p.grants == 0 {
            p = self.cv.wait(p).unwrap();
        }
        p.grants -= 1;
    }

    pub(crate) fn release(&self) {
        let mut p = self.par.lock().unwrap();
        if p.waiting == 0 {
            p.running -= 1;
            return;
        }
        p.waiting -= 1;
        p.grants += 1;
        self.cv.notify_one();
    }
}

/// A one-shot gate that is opened once (Go's `close(t.barrier)`).
#[derive(Default)]
pub(crate) struct Barrier {
    open: Mutex<bool>,
    cv: Condvar,
}

impl Barrier {
    pub(crate) fn open(&self) {
        *self.open.lock().unwrap() = true;
        self.cv.notify_all();
    }

    pub(crate) fn wait(&self) {
        let mut g = self.open.lock().unwrap();
        while !*g {
            g = self.cv.wait(g).unwrap();
        }
    }
}

