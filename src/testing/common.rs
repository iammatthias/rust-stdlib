/// Go's `testing.common`, shared (`Arc`) between a test and its children.
#[derive(Clone)]
pub(crate) struct Common(pub(crate) Arc<Shared>);

impl std::ops::Deref for Common {
    type Target = Shared;
    fn deref(&self) -> &Shared {
        &self.0
    }
}

pub(crate) struct CommonSpec {
    pub(crate) name: String,
    pub(crate) parent: Option<Common>,
    pub(crate) level: usize,
    pub(crate) chatty: Option<Arc<Chatty>>,
    pub(crate) sink: Arc<Sink>,
    pub(crate) bench: bool,
    pub(crate) tstate: Arc<TestState>,
    pub(crate) module_path: String,
    pub(crate) import_path: String,
}

impl Common {
    pub(crate) fn new(spec: CommonSpec) -> Common {
        let (tx, rx) = mpsc::channel();
        Common(Arc::new(Shared {
            name: spec.name,
            parent: spec.parent,
            level: spec.level,
            chatty: spec.chatty,
            sink: spec.sink,
            bench: spec.bench,
            tstate: spec.tstate,
            module_path: spec.module_path,
            import_path: spec.import_path,
            ctx: Mutex::new(Context::background().with_cancel()),
            inner: Mutex::new(Inner {
                output: String::new(),
                partial: String::new(),
                failed: false,
                skipped: false,
                finished: false,
                done: false,
                ran: false,
                is_parallel: false,
                deny_parallel: false,
                parallel_capable: false,
                par_held: false,
                cleanups: Vec::new(),
                temp_dir: None,
                temp_dir_err: None,
                temp_dir_seq: 0,
                artifact_dir: None,
                duration: Duration::ZERO,
                start: Instant::now(),
                sub: Vec::new(),
            }),
            barrier: Barrier::default(),
            signal_tx: tx,
            signal_rx: Mutex::new(rx),
            has_sub: AtomicBool::new(false),
            cleanup_started: AtomicBool::new(false),
            is_synctest: AtomicBool::new(false),
        }))
    }

    pub(crate) fn lock(&self) -> MutexGuard<'_, Inner> {
        self.inner.lock().unwrap_or_else(|e| e.into_inner())
    }

    pub(crate) fn child_spec(&self, name: String) -> CommonSpec {
        CommonSpec {
            name,
            parent: Some(self.clone()),
            level: self.level + 1,
            chatty: self.chatty.clone(),
            sink: self.sink.clone(),
            bench: self.bench,
            tstate: self.tstate.clone(),
            module_path: self.module_path.clone(),
            import_path: self.import_path.clone(),
        }
    }

    pub(crate) fn context(&self) -> Context {
        self.ctx.lock().unwrap().0.clone()
    }

    /// Replaces the context with a fresh one (benchmarks do this per run).
    pub(crate) fn reset_context(&self) {
        *self.ctx.lock().unwrap() = Context::background().with_cancel();
    }

    pub(crate) fn send_signal(&self, v: bool) {
        let _ = self.signal_tx.send(v);
    }

    pub(crate) fn recv_signal(&self) -> bool {
        self.signal_rx
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .recv()
            .unwrap_or(true)
    }

    pub(crate) fn set_ran(&self) {
        if let Some(p) = &self.parent {
            p.set_ran();
        }
        self.lock().ran = true;
    }

    pub(crate) fn fail(&self) {
        if let Some(p) = &self.parent {
            p.fail();
        }
        let mut g = self.lock();
        if g.done {
            let name = self.name.clone();
            drop(g);
            panic!("Fail in goroutine after {name} has completed");
        }
        g.failed = true;
    }

    pub(crate) fn failed(&self) -> bool {
        self.lock().failed
    }

    pub(crate) fn skipped(&self) -> bool {
        self.lock().skipped
    }

    pub(crate) fn fail_now(&self) -> ! {
        self.fail();
        self.lock().finished = true;
        goexit()
    }

    pub(crate) fn skip_now(&self) -> ! {
        {
            let mut g = self.lock();
            g.skipped = true;
            g.finished = true;
        }
        goexit()
    }

    /// The test to which output should be appended: this one if incomplete,
    /// else its closest incomplete ancestor.
    pub(crate) fn destination(&self) -> Option<Common> {
        if !self.lock().done && !self.is_synctest.load(Ordering::SeqCst) {
            return Some(self.clone());
        }
        let mut cur = self.parent.clone();
        while let Some(p) = cur {
            if !p.lock().done {
                return Some(p);
            }
            cur = p.parent.clone();
        }
        None
    }

    fn call_site(&self, loc: &Location<'_>) -> String {
        let file = loc.file();
        let file = if self.tstate.fullpath {
            file
        } else {
            file.rsplit(['/', '\\']).next().unwrap_or(file)
        };
        let file = if file.is_empty() { "???" } else { file };
        format!("{file}:{}: ", loc.line().max(1))
    }

    pub(crate) fn log_at(&self, loc: &Location<'_>, s: &str, _is_err: bool) {
        let mut s = s.strip_suffix('\n').unwrap_or(s).replace('\n', "\n    ");
        s.push('\n');
        let Some(n) = self.destination() else {
            panic!("Log in goroutine after {} has completed: {}", self.name, s);
        };
        let s = format!("{}{}", n.call_site(loc), s);
        n.flush_partial();
        n.o_write(&s);
    }

    /// Appends text to the output as `log` would, without a call site.
    pub(crate) fn log_plain(&self, s: &str) {
        let mut s = s.strip_suffix('\n').unwrap_or(s).replace('\n', "\n    ");
        s.push('\n');
        if let Some(n) = self.destination() {
            n.flush_partial();
            n.o_write(&s);
        }
    }

    pub(crate) fn flush_partial(&self) {
        let partial = !self.lock().partial.is_empty();
        if partial {
            self.o_write("\n");
        }
    }

    /// Go's `outputWriter.write`: buffers partial lines, indents whole ones.
    pub(crate) fn o_write(&self, p: &str) {
        let mut g = self.lock();
        let mut data = std::mem::take(&mut g.partial);
        data.push_str(p);
        let cut = data.rfind('\n').map_or(0, |i| i + 1);
        let (lines, rest) = data.split_at(cut);
        for line in lines.split_inclusive('\n') {
            self.write_line(&mut g, line);
        }
        g.partial = rest.to_string();
    }

    fn write_line(&self, g: &mut Inner, line: &str) {
        match &self.chatty {
            Some(chatty) if !g.done => {
                let text = format!("{INDENT}{line}");
                if self.bench {
                    self.sink.write(&text);
                } else {
                    chatty.printf(&self.name, &text);
                }
            }
            _ => {
                g.output.push_str(INDENT);
                g.output.push_str(line);
            }
        }
    }

    /// Writes `text` to the parent's output as the parent's indenter would.
    fn indent_into(g: &mut Inner, text: &str) {
        for line in text.split_inclusive('\n') {
            g.output.push_str(INDENT);
            g.output.push_str(line);
        }
    }

    /// Writes `header` and then c.output to the parent.
    pub(crate) fn flush_to_parent(&self, test_name: &str, header: &str) {
        let p = self
            .parent
            .as_ref()
            .expect("flush_to_parent needs a parent");
        let mut pg = p.lock();
        let mut cg = self.lock();
        let mut text = header.to_string();
        if !cg.output.is_empty() {
            text.push_str(&cg.output);
            cg.output.clear();
        }
        let parent_is_root = p.parent.is_none();
        if parent_is_root {
            match &self.chatty {
                Some(chatty) => chatty.updatef(test_name, &text),
                None => self.sink.write(&text),
            }
        } else {
            Common::indent_into(&mut pg, &text);
        }
    }

    // ----- the TB surface -----

    pub(crate) fn cleanup(&self, f: Box<dyn FnOnce() + Send>) {
        self.lock().cleanups.push(f);
    }

    /// Runs the registered cleanups, last added first. Returns the message of
    /// the first real panic (cleanups that call `fatal` merely stop).
    pub(crate) fn run_cleanup(&self) -> Option<String> {
        self.cleanup_started.store(true, Ordering::SeqCst);
        let cancel = self.ctx.lock().unwrap().1.clone();
        cancel();
        let mut first = None;
        loop {
            let f = self.lock().cleanups.pop();
            let Some(f) = f else { break };
            if let Err(p) = panic::catch_unwind(panic::AssertUnwindSafe(f)) {
                if !is_goexit(&*p) && first.is_none() {
                    first = Some(panic_message(&*p));
                }
            }
        }
        self.cleanup_started.store(false, Ordering::SeqCst);
        first
    }

    pub(crate) fn make_temp_dir(&self) -> Result<String, String> {
        let mut g = self.lock();
        let non_existent = match &g.temp_dir {
            None => true,
            Some(d) => match std::fs::metadata(d) {
                Ok(_) => false,
                Err(e) if e.kind() == io::ErrorKind::NotFound => true,
                Err(e) => return Err(e.to_string()),
            },
        };
        if non_existent {
            let mut pattern: String = self.name.chars().take(64).collect();
            // Limit by bytes like Go (invalid slices are dropped by the filter).
            while pattern.len() > 64 {
                pattern.pop();
            }
            let allowed = "!#$%&()+,-.=@^_{}~ ";
            let pattern = remove_symbols_except(&pattern, allowed);
            let base = std::env::var_os("GOTMPDIR")
                .map(PathBuf::from)
                .unwrap_or_else(std::env::temp_dir);
            match mkdir_temp(&base, &pattern) {
                Ok(d) => {
                    g.temp_dir = Some(d.clone());
                    g.temp_dir_err = None;
                    let me = self.clone();
                    g.cleanups.push(Box::new(move || {
                        if let Err(e) = std::fs::remove_dir_all(&d) {
                            if e.kind() != io::ErrorKind::NotFound {
                                me.log_plain(&format!("TempDir RemoveAll cleanup: {e}"));
                                me.fail();
                            }
                        }
                    }));
                }
                Err(e) => g.temp_dir_err = Some(e.to_string()),
            }
        }
        if let Some(e) = &g.temp_dir_err {
            return Err(e.clone());
        }
        g.temp_dir_seq += 1;
        let seq = g.temp_dir_seq;
        let dir = format!(
            "{}{}{:03}",
            g.temp_dir.as_ref().unwrap().display(),
            std::path::MAIN_SEPARATOR,
            seq
        );
        drop(g);
        std::fs::create_dir(&dir).map_err(|e| e.to_string())?;
        Ok(dir)
    }

    pub(crate) fn relative_artifact_base(&self) -> String {
        const MAX_NAME: usize = 64;
        let mut name = self.name.replace('/', "__");
        if name.len() > MAX_NAME {
            let h = format!("{:x}", hash_string(&name));
            let mut cut = MAX_NAME.saturating_sub(h.len());
            while !name.is_char_boundary(cut) {
                cut -= 1;
            }
            name = format!("{}{}", &name[..cut], h);
        }
        let pkg = self
            .import_path
            .strip_prefix(self.module_path.as_str())
            .unwrap_or(&self.import_path);
        let pkg = pkg.strip_prefix('/').unwrap_or(pkg);
        let base = if pkg.is_empty() {
            name
        } else {
            format!("{pkg}/{name}")
        };
        remove_symbols_except(&base, "!#$%&()+,-.=@^_{}~ /")
    }
}

pub(crate) fn hash_string(s: &str) -> u64 {
    let mut h: u64 = 0;
    for b in s.bytes() {
        h ^= u64::from(b);
        h = h.wrapping_mul(1099511628211);
    }
    h
}

pub(crate) fn remove_symbols_except(s: &str, allowed: &str) -> String {
    s.chars()
        .filter(|&r| r.is_alphabetic() || r.is_numeric() || allowed.contains(r))
        .collect()
}

/// Like Go's `os.MkdirTemp`: `pattern` with a random decimal suffix.
pub(crate) fn mkdir_temp(base: &std::path::Path, pattern: &str) -> io::Result<PathBuf> {
    use std::sync::atomic::AtomicU64;
    static SEQ: AtomicU64 = AtomicU64::new(0);
    let (prefix, suffix) = match pattern.rfind('*') {
        Some(i) => (&pattern[..i], &pattern[i + 1..]),
        None => (pattern, ""),
    };
    for _ in 0..10_000 {
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.subsec_nanos() as u64);
        let r = (u64::from(std::process::id()) << 32)
            ^ nanos
            ^ SEQ
                .fetch_add(1, Ordering::Relaxed)
                .wrapping_mul(0x9E37_79B9);
        let path = base.join(format!("{prefix}{}{suffix}", r % 1_000_000_000));
        match std::fs::create_dir(&path) {
            Ok(()) => return Ok(path),
            Err(e) if e.kind() == io::ErrorKind::AlreadyExists => continue,
            Err(e) => return Err(e),
        }
    }
    Err(io::Error::new(
        io::ErrorKind::AlreadyExists,
        "mkdirtemp: too many attempts",
    ))
}

/// The writer returned by [`TB::output`]: Go's `outputWriter`.
pub struct OutputWriter {
    pub(crate) c: Common,
}

impl io::Write for OutputWriter {
    fn write(&mut self, p: &[u8]) -> io::Result<usize> {
        let Some(n) = self.c.destination() else {
            panic!("Write called after {} has completed", self.c.name);
        };
        n.o_write(&String::from_utf8_lossy(p));
        Ok(p.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

/// Formats `args` like Go's `fmt.Sprintln`: operands separated by spaces and a
/// final newline.
pub(crate) fn sprintln(args: &[&dyn Display]) -> String {
    let mut s = String::new();
    for (i, a) in args.iter().enumerate() {
        if i > 0 {
            s.push(' ');
        }
        s.push_str(&a.to_string());
    }
    s.push('\n');
    s
}

/// Go's `testing.TB`: the interface common to [`T`](super::T),
/// [`B`](super::B) and [`F`](super::F).
///
/// `log`, `error`, `fatal` and `skip` take their operands as a slice and
/// format them like `fmt.Sprintln`; the `*f` variants take
/// `format_args!(...)`. Report locations come from `#[track_caller]`, so a
/// Rust helper marked `#[track_caller]` is skipped in the reported
/// `file:line`, which is what `Helper` does in Go.
pub trait TB: Send + Sync {
    /// Go's `ArtifactDir`.
    #[track_caller]
    fn artifact_dir(&self) -> String;
    /// Go's `Attr`.
    #[track_caller]
    fn attr(&self, key: &str, value: &str);
    /// Go's `Cleanup`: `f` runs when the test and its subtests complete, last
    /// added first.
    fn cleanup(&self, f: Box<dyn FnOnce() + Send + 'static>);
    /// Go's `Context`.
    fn context(&self) -> Context;
    /// Go's `Error`: `log` followed by `fail`.
    #[track_caller]
    fn error(&self, args: &[&dyn Display]);
    /// Go's `Errorf`.
    #[track_caller]
    fn errorf(&self, args: fmt::Arguments<'_>);
    /// Go's `Fail`.
    fn fail(&self);
    /// Go's `FailNow`: unwinds with the [`Goexit`] payload.
    fn fail_now(&self) -> !;
    /// Go's `Failed`.
    fn failed(&self) -> bool;
    /// Go's `Fatal`: `log` followed by `fail_now`.
    #[track_caller]
    fn fatal(&self, args: &[&dyn Display]) -> !;
    /// Go's `Fatalf`.
    #[track_caller]
    fn fatalf(&self, args: fmt::Arguments<'_>) -> !;
    /// Go's `Helper`. Rust finds the reported location through
    /// `#[track_caller]` on the helper function, so this is a marker only.
    #[track_caller]
    fn helper(&self);
    /// Go's `Log`.
    #[track_caller]
    fn log(&self, args: &[&dyn Display]);
    /// Go's `Logf`.
    #[track_caller]
    fn logf(&self, args: fmt::Arguments<'_>);
    /// Go's `Name`.
    fn name(&self) -> String;
    /// Go's `Output`.
    fn output(&self) -> Box<dyn io::Write + Send>;
    /// Go's `Setenv`.
    #[track_caller]
    fn setenv(&self, key: &str, value: &str);
    /// Go's `Chdir`.
    #[track_caller]
    fn chdir(&self, dir: &str);
    /// Go's `Skip`.
    #[track_caller]
    fn skip(&self, args: &[&dyn Display]) -> !;
    /// Go's `SkipNow`.
    fn skip_now(&self) -> !;
    /// Go's `Skipf`.
    #[track_caller]
    fn skipf(&self, args: fmt::Arguments<'_>) -> !;
    /// Go's `Skipped`.
    fn skipped(&self) -> bool;
    /// Go's `TempDir`.
    #[track_caller]
    fn temp_dir(&self) -> String;
}

impl Common {
    #[track_caller]
    pub(crate) fn tb_log(&self, args: &[&dyn Display]) {
        self.log_at(Location::caller(), &sprintln(args), false);
    }
    #[track_caller]
    pub(crate) fn tb_logf(&self, args: fmt::Arguments<'_>) {
        self.log_at(Location::caller(), &args.to_string(), false);
    }
    #[track_caller]
    pub(crate) fn tb_error(&self, args: &[&dyn Display]) {
        self.log_at(Location::caller(), &sprintln(args), true);
        self.fail();
    }
    #[track_caller]
    pub(crate) fn tb_errorf(&self, args: fmt::Arguments<'_>) {
        self.log_at(Location::caller(), &args.to_string(), true);
        self.fail();
    }
    #[track_caller]
    pub(crate) fn tb_fatal(&self, args: &[&dyn Display]) -> ! {
        self.log_at(Location::caller(), &sprintln(args), true);
        self.fail_now()
    }
    #[track_caller]
    pub(crate) fn tb_fatalf(&self, args: fmt::Arguments<'_>) -> ! {
        self.log_at(Location::caller(), &args.to_string(), true);
        self.fail_now()
    }
    #[track_caller]
    pub(crate) fn tb_skip(&self, args: &[&dyn Display]) -> ! {
        self.log_at(Location::caller(), &sprintln(args), false);
        self.skip_now()
    }
    #[track_caller]
    pub(crate) fn tb_skipf(&self, args: fmt::Arguments<'_>) -> ! {
        self.log_at(Location::caller(), &args.to_string(), false);
        self.skip_now()
    }
    #[track_caller]
    pub(crate) fn tb_temp_dir(&self) -> String {
        let loc = Location::caller();
        match self.make_temp_dir() {
            Ok(d) => d,
            Err(e) => {
                self.log_at(loc, &format!("TempDir: {e}"), true);
                self.fail_now()
            }
        }
    }
    #[track_caller]
    pub(crate) fn tb_artifact_dir(&self) -> String {
        let loc = Location::caller();
        let cached = self.lock().artifact_dir.clone();
        let result = match cached {
            Some(r) => r,
            None => {
                let r = self.make_artifact_dir();
                self.lock().artifact_dir = Some(r.clone());
                r
            }
        };
        match result {
            Ok(d) => d,
            Err(e) => {
                self.log_at(loc, &format!("ArtifactDir: {e}"), true);
                self.fail_now()
            }
        }
    }
    fn make_artifact_dir(&self) -> Result<String, String> {
        let flags = super::flags();
        if !flags.artifacts {
            return self.make_temp_dir();
        }
        let base = PathBuf::from(&flags.outputdir)
            .join("_artifacts")
            .join(self.relative_artifact_base());
        std::fs::create_dir_all(&base).map_err(|e| e.to_string())?;
        let dir = mkdir_temp(&base, "").map_err(|e| e.to_string())?;
        if let Some(c) = &self.chatty {
            c.updatef(
                &self.name,
                &format!("=== ARTIFACTS {} {}\n", self.name, dir.display()),
            );
        }
        Ok(dir.display().to_string())
    }
    #[track_caller]
    pub(crate) fn tb_setenv(&self, key: &str, value: &str) {
        let loc = Location::caller();
        let prev = std::env::var_os(key);
        if key.is_empty() || key.contains(['=', '\0']) || value.contains('\0') {
            self.log_at(
                loc,
                &format!("cannot set environment variable: setenv {key}: invalid argument"),
                true,
            );
            self.fail_now();
        }
        std::env::set_var(key, value);
        let key = key.to_string();
        self.cleanup(Box::new(move || match prev {
            Some(v) => std::env::set_var(&key, v),
            None => std::env::remove_var(&key),
        }));
    }
    #[track_caller]
    pub(crate) fn tb_chdir(&self, dir: &str) {
        let loc = Location::caller();
        let old = match std::env::current_dir() {
            Ok(d) => d,
            Err(e) => {
                self.log_at(loc, &e.to_string(), true);
                self.fail_now()
            }
        };
        if let Err(e) = std::env::set_current_dir(dir) {
            self.log_at(loc, &format!("chdir {dir}: {e}"), true);
            self.fail_now();
        }
        let abs = if std::path::Path::new(dir).is_absolute() {
            dir.to_string()
        } else {
            match std::env::current_dir() {
                Ok(d) => d.display().to_string(),
                Err(e) => {
                    self.log_at(loc, &e.to_string(), true);
                    self.fail_now()
                }
            }
        };
        self.tb_setenv("PWD", &abs);
        self.cleanup(Box::new(move || {
            if let Err(e) = std::env::set_current_dir(&old) {
                panic!("testing.Chdir: {e}");
            }
        }));
    }
    pub(crate) fn tb_attr(&self, loc: &Location<'_>, key: &str, value: &str) {
        if key.chars().any(char::is_whitespace) {
            self.log_at(
                loc,
                &format!(
                    "disallowed whitespace in attribute key {}",
                    crate::strconv::quote(key)
                ),
                true,
            );
            self.fail();
            return;
        }
        if value.contains(['\r', '\n']) {
            self.log_at(
                loc,
                &format!(
                    "disallowed newline in attribute value {}",
                    crate::strconv::quote(value)
                ),
                true,
            );
            self.fail();
            return;
        }
        if let Some(c) = &self.chatty {
            c.updatef(
                &self.name,
                &format!("=== ATTR  {} {key} {value}\n", self.name),
            );
        }
    }
    pub(crate) fn tb_output(&self) -> OutputWriter {
        if self.destination().is_none() {
            panic!("Output called after {} has completed", self.name);
        }
        OutputWriter { c: self.clone() }
    }
}

/// Implements [`TB`] for a type with a `c: Common` field.
macro_rules! impl_tb {
    ($ty:ty) => {
        impl $crate::testing::TB for $ty {
            #[track_caller]
            fn artifact_dir(&self) -> String {
                self.c.tb_artifact_dir()
            }
            #[track_caller]
            fn attr(&self, key: &str, value: &str) {
                self.c.tb_attr(::std::panic::Location::caller(), key, value)
            }
            fn cleanup(&self, f: Box<dyn FnOnce() + Send + 'static>) {
                self.c.cleanup(f)
            }
            fn context(&self) -> $crate::context::Context {
                self.c.context()
            }
            #[track_caller]
            fn error(&self, args: &[&dyn ::std::fmt::Display]) {
                self.c.tb_error(args)
            }
            #[track_caller]
            fn errorf(&self, args: ::std::fmt::Arguments<'_>) {
                self.c.tb_errorf(args)
            }
            fn fail(&self) {
                self.c.fail()
            }
            fn fail_now(&self) -> ! {
                self.c.fail_now()
            }
            fn failed(&self) -> bool {
                self.c.failed()
            }
            #[track_caller]
            fn fatal(&self, args: &[&dyn ::std::fmt::Display]) -> ! {
                self.c.tb_fatal(args)
            }
            #[track_caller]
            fn fatalf(&self, args: ::std::fmt::Arguments<'_>) -> ! {
                self.c.tb_fatalf(args)
            }
            #[track_caller]
            fn helper(&self) {}
            #[track_caller]
            fn log(&self, args: &[&dyn ::std::fmt::Display]) {
                self.c.tb_log(args)
            }
            #[track_caller]
            fn logf(&self, args: ::std::fmt::Arguments<'_>) {
                self.c.tb_logf(args)
            }
            fn name(&self) -> String {
                self.c.name.clone()
            }
            fn output(&self) -> Box<dyn ::std::io::Write + Send> {
                Box::new(self.c.tb_output())
            }
            #[track_caller]
            fn setenv(&self, key: &str, value: &str) {
                self.setenv_impl(key, value)
            }
            #[track_caller]
            fn chdir(&self, dir: &str) {
                self.chdir_impl(dir)
            }
            #[track_caller]
            fn skip(&self, args: &[&dyn ::std::fmt::Display]) -> ! {
                self.c.tb_skip(args)
            }
            fn skip_now(&self) -> ! {
                self.c.skip_now()
            }
            #[track_caller]
            fn skipf(&self, args: ::std::fmt::Arguments<'_>) -> ! {
                self.c.tb_skipf(args)
            }
            fn skipped(&self) -> bool {
                self.c.skipped()
            }
            #[track_caller]
            fn temp_dir(&self) -> String {
                self.c.tb_temp_dir()
            }
        }
    };
}
pub(crate) use impl_tb;
