/// Go's `math.J0`: the order-zero Bessel function of the first kind.
///
/// Special cases: `j0(±Inf) = 0`, `j0(0) = 1`, `j0(NaN) = NaN`.
pub fn j0(mut x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }
    if x.is_infinite() {
        return 0.0;
    }
    if x == 0.0 {
        return 1.0;
    }
    x = x.abs();
    if x >= 2.0 {
        let (s, c) = super::sincos(x);
        let mut ss = s - c;
        let mut cc = s + c;
        // j0(x) = 1/sqrt(pi) * (P(0,x)*cc - Q(0,x)*ss) / sqrt(x)
        // y0(x) = 1/sqrt(pi) * (P(0,x)*ss + Q(0,x)*cc) / sqrt(x)
        if x < f64::MAX / 2.0 {
            // make sure x+x does not overflow
            let z = -super::cos(x + x);
            if s * c < 0.0 {
                cc = z / ss;
            } else {
                ss = z / cc;
            }
        }
        // j0(x) = 1/sqrt(pi) * (P(0,x)*cc - Q(0,x)*ss) / sqrt(x)
        let z = if x > TWO129 {
            (1.0 / SQRT_PI) * cc / x.sqrt()
        } else {
            let u = pzero(x);
            let v = qzero(x);
            (1.0 / SQRT_PI) * (u * cc - v * ss) / x.sqrt()
        };
        return z;
    }
    if x < TWO_M13 {
        // |x| < ~1.2207e-4
        if x < TWO_M27 {
            return 1.0;
        }
        return 1.0 - 0.25 * x * x;
    }
    let z = x * x;
    let r = z * (J0_R02 + z * (J0_R03 + z * (J0_R04 + z * J0_R05)));
    let s = 1.0 + z * (J0_S01 + z * (J0_S02 + z * (J0_S03 + z * J0_S04)));
    if x < 1.0 {
        return 1.0 + z * (-0.25 + (r / s));
    }
    let u = 0.5 * x;
    (1.0 + u) * (1.0 - u) + z * (r / s)
}

/// Go's `math.Y0`: the order-zero Bessel function of the second kind.
///
/// Special cases: `y0(+Inf) = 0`, `y0(0) = -Inf`, `y0(x < 0) = NaN`,
/// `y0(NaN) = NaN`.
pub fn y0(x: f64) -> f64 {
    if x < 0.0 || x.is_nan() {
        return nan();
    }
    if is_inf(x, 1) {
        return 0.0;
    }
    if x == 0.0 {
        return inf(-1);
    }
    if x >= 2.0 {
        let (s, c) = super::sincos(x);
        let mut ss = s - c;
        let mut cc = s + c;
        if x < f64::MAX / 2.0 {
            let z = -super::cos(x + x);
            if s * c < 0.0 {
                cc = z / ss;
            } else {
                ss = z / cc;
            }
        }
        return if x > TWO129 {
            (1.0 / SQRT_PI) * ss / x.sqrt()
        } else {
            let u = pzero(x);
            let v = qzero(x);
            (1.0 / SQRT_PI) * (u * ss + v * cc) / x.sqrt()
        };
    }
    if x <= TWO_M27 {
        return Y0_U00 + (2.0 / PI) * super::log(x);
    }
    let z = x * x;
    let u = Y0_U00
        + z * (Y0_U01 + z * (Y0_U02 + z * (Y0_U03 + z * (Y0_U04 + z * (Y0_U05 + z * Y0_U06)))));
    let v = 1.0 + z * (Y0_V01 + z * (Y0_V02 + z * (Y0_V03 + z * Y0_V04)));
    u / v + (2.0 / PI) * j0(x) * super::log(x)
}

fn pzero(x: f64) -> f64 {
    let (p, q): (&[f64; 6], &[f64; 5]) = if x >= 8.0 {
        (&P0R8, &P0S8)
    } else if x >= 4.5454 {
        (&P0R5, &P0S5)
    } else if x >= 2.8571 {
        (&P0R3, &P0S3)
    } else {
        (&P0R2, &P0S2)
    };
    let z = 1.0 / (x * x);
    let r = p[0] + z * (p[1] + z * (p[2] + z * (p[3] + z * (p[4] + z * p[5]))));
    let s = 1.0 + z * (q[0] + z * (q[1] + z * (q[2] + z * (q[3] + z * q[4]))));
    1.0 + r / s
}

fn qzero(x: f64) -> f64 {
    let (p, q): (&[f64; 6], &[f64; 6]) = if x >= 8.0 {
        (&Q0R8, &Q0S8)
    } else if x >= 4.5454 {
        (&Q0R5, &Q0S5)
    } else if x >= 2.8571 {
        (&Q0R3, &Q0S3)
    } else {
        (&Q0R2, &Q0S2)
    };
    let z = 1.0 / (x * x);
    let r = p[0] + z * (p[1] + z * (p[2] + z * (p[3] + z * (p[4] + z * p[5]))));
    let s = 1.0 + z * (q[0] + z * (q[1] + z * (q[2] + z * (q[3] + z * (q[4] + z * q[5])))));
    (-0.125 + r / s) / x
}

/// Go's `math.J1`: the order-one Bessel function of the first kind.
///
/// Special cases: `j1(±Inf) = 0`, `j1(NaN) = NaN`.
pub fn j1(mut x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }
    if x.is_infinite() || x == 0.0 {
        return 0.0;
    }
    let mut sign = false;
    if x < 0.0 {
        x = -x;
        sign = true;
    }
    if x >= 2.0 {
        let (s, c) = super::sincos(x);
        let mut ss = -s - c;
        let mut cc = s - c;
        if x < f64::MAX / 2.0 {
            let z = super::cos(x + x);
            if s * c > 0.0 {
                cc = z / ss;
            } else {
                ss = z / cc;
            }
        }
        let z = if x > TWO129 {
            (1.0 / SQRT_PI) * cc / x.sqrt()
        } else {
            let u = pone(x);
            let v = qone(x);
            (1.0 / SQRT_PI) * (u * cc - v * ss) / x.sqrt()
        };
        return if sign { -z } else { z };
    }
    if x < TWO_M27 {
        return 0.5 * x;
    }
    let z = x * x;
    let mut r = z * (J1_R00 + z * (J1_R01 + z * (J1_R02 + z * J1_R03)));
    let s = 1.0 + z * (J1_S01 + z * (J1_S02 + z * (J1_S03 + z * (J1_S04 + z * J1_S05))));
    r *= x;
    let z = 0.5 * x + r / s;
    if sign {
        -z
    } else {
        z
    }
}

/// Go's `math.Y1`: the order-one Bessel function of the second kind.
///
/// Special cases: `y1(+Inf) = 0`, `y1(0) = -Inf`, `y1(x < 0) = NaN`,
/// `y1(NaN) = NaN`.
pub fn y1(x: f64) -> f64 {
    if x < 0.0 || x.is_nan() {
        return nan();
    }
    if is_inf(x, 1) {
        return 0.0;
    }
    if x == 0.0 {
        return inf(-1);
    }
    if x >= 2.0 {
        let (s, c) = super::sincos(x);
        let mut ss = -s - c;
        let mut cc = s - c;
        if x < f64::MAX / 2.0 {
            let z = super::cos(x + x);
            if s * c > 0.0 {
                cc = z / ss;
            } else {
                ss = z / cc;
            }
        }
        return if x > TWO129 {
            (1.0 / SQRT_PI) * ss / x.sqrt()
        } else {
            let u = pone(x);
            let v = qone(x);
            (1.0 / SQRT_PI) * (u * ss + v * cc) / x.sqrt()
        };
    }
    if x <= TWO_M54 {
        return -(2.0 / PI) / x;
    }
    let z = x * x;
    let u = Y1_U00 + z * (Y1_U01 + z * (Y1_U02 + z * (Y1_U03 + z * Y1_U04)));
    let v = 1.0 + z * (Y1_V00 + z * (Y1_V01 + z * (Y1_V02 + z * (Y1_V03 + z * Y1_V04))));
    x * (u / v) + (2.0 / PI) * (j1(x) * super::log(x) - 1.0 / x)
}

fn pone(x: f64) -> f64 {
    let (p, q): (&[f64; 6], &[f64; 5]) = if x >= 8.0 {
        (&P1R8, &P1S8)
    } else if x >= 4.5454 {
        (&P1R5, &P1S5)
    } else if x >= 2.8571 {
        (&P1R3, &P1S3)
    } else {
        (&P1R2, &P1S2)
    };
    let z = 1.0 / (x * x);
    let r = p[0] + z * (p[1] + z * (p[2] + z * (p[3] + z * (p[4] + z * p[5]))));
    let s = 1.0 + z * (q[0] + z * (q[1] + z * (q[2] + z * (q[3] + z * q[4]))));
    1.0 + r / s
}

fn qone(x: f64) -> f64 {
    let (p, q): (&[f64; 6], &[f64; 6]) = if x >= 8.0 {
        (&Q1R8, &Q1S8)
    } else if x >= 4.5454 {
        (&Q1R5, &Q1S5)
    } else if x >= 2.8571 {
        (&Q1R3, &Q1S3)
    } else {
        (&Q1R2, &Q1S2)
    };
    let z = 1.0 / (x * x);
    let r = p[0] + z * (p[1] + z * (p[2] + z * (p[3] + z * (p[4] + z * p[5]))));
    let s = 1.0 + z * (q[0] + z * (q[1] + z * (q[2] + z * (q[3] + z * (q[4] + z * q[5])))));
    (0.375 + r / s) / x
}

/// Go's `math.Jn`: the order-n Bessel function of the first kind.
///
/// Special cases: `jn(n, ±Inf) = 0`, `jn(n, NaN) = NaN`.
pub fn jn(mut n: i64, mut x: f64) -> f64 {
    if x.is_nan() {
        return x;
    }
    if x.is_infinite() {
        return 0.0;
    }
    if n == 0 {
        return j0(x);
    }
    if x == 0.0 {
        return 0.0;
    }
    if n < 0 {
        n = -n;
        x = -x;
    }
    if n == 1 {
        return j1(x);
    }
    let mut sign = false;
    if x < 0.0 {
        x = -x;
        if n & 1 == 1 {
            sign = true; // odd n and negative x
        }
    }
    let mut b;
    if n as f64 <= x {
        // Safe to use J(n+1,x)=2n/x *J(n,x)-J(n-1,x)
        if x >= TWO302 {
            // x > 2**302
            let (s, c) = super::sincos(x);
            let temp = match n & 3 {
                0 => c + s,
                1 => -c + s,
                2 => -c - s,
                _ => c - s,
            };
            b = (1.0 / SQRT_PI) * temp / x.sqrt();
        } else {
            b = j1(x);
            let mut a = j0(x);
            let mut i = 1;
            while i < n {
                let next = b * ((i + i) as f64 / x) - a; // avoid underflow
                a = b;
                b = next;
                i += 1;
            }
        }
    } else if x < TWO_M29 {
        // x < 2**-29
        if n > 33 {
            // underflow
            b = 0.0;
        } else {
            let temp = x * 0.5;
            b = temp;
            let mut a = 1.0;
            let mut i = 2;
            while i <= n {
                a *= i as f64; // a = n!
                b *= temp; // b = (x/2)**n
                i += 1;
            }
            b /= a;
        }
    } else {
        // use backward recurrence
        let w = (n + n) as f64 / x;
        let h = 2.0 / x;
        let mut q0 = w;
        let mut z = w + h;
        let mut q1 = w * z - 1.0;
        let mut k = 1;
        while q1 < 1e9 {
            k += 1;
            z += h;
            let next = z * q1 - q0;
            q0 = q1;
            q1 = next;
        }
        let m = n + n;
        let mut t = 0.0;
        let mut i = 2 * (n + k);
        while i >= m {
            t = 1.0 / (i as f64 / x - t);
            i -= 2;
        }
        let mut a = t;
        b = 1.0;
        let mut tmp = n as f64;
        let v = 2.0 / x;
        tmp *= super::log((v * tmp).abs());
        if tmp < 7.09782712893383973096e+02 {
            let mut i = n - 1;
            while i > 0 {
                let di = (i + i) as f64;
                let next = b * di / x - a;
                a = b;
                b = next;
                i -= 1;
            }
        } else {
            let mut i = n - 1;
            while i > 0 {
                let di = (i + i) as f64;
                let next = b * di / x - a;
                a = b;
                b = next;
                // scale b to avoid spurious overflow
                if b > 1e100 {
                    a /= b;
                    t /= b;
                    b = 1.0;
                }
                i -= 1;
            }
        }
        b = t * j0(x) / b;
    }
    if sign {
        -b
    } else {
        b
    }
}

/// Go's `math.Yn`: the order-n Bessel function of the second kind.
///
/// Special cases: `yn(n, +Inf) = 0`, `yn(n >= 0, 0) = -Inf`, `yn(n < 0, 0) =
/// +Inf` if n is odd and `-Inf` if even, `yn(n, x < 0) = NaN`, `yn(n, NaN) =
/// NaN`.
pub fn yn(mut n: i64, x: f64) -> f64 {
    if x < 0.0 || x.is_nan() {
        return nan();
    }
    if is_inf(x, 1) {
        return 0.0;
    }
    if n == 0 {
        return y0(x);
    }
    if x == 0.0 {
        if n < 0 && n & 1 == 1 {
            return inf(1);
        }
        return inf(-1);
    }
    let mut sign = false;
    if n < 0 {
        n = -n;
        if n & 1 == 1 {
            sign = true; // sign true if n < 0 && |n| odd
        }
    }
    if n == 1 {
        return if sign { -y1(x) } else { y1(x) };
    }
    let mut b;
    if x >= TWO302 {
        // x > 2**302
        let (s, c) = super::sincos(x);
        let temp = match n & 3 {
            0 => s - c,
            1 => -s - c,
            2 => -s + c,
            _ => s + c,
        };
        b = (1.0 / SQRT_PI) * temp / x.sqrt();
    } else {
        let mut a = y0(x);
        b = y1(x);
        // quit if b is -inf
        let mut i = 1;
        while i < n && !is_inf(b, -1) {
            let next = ((i + i) as f64 / x) * b - a;
            a = b;
            b = next;
            i += 1;
        }
    }
    if sign {
        -b
    } else {
        b
    }
}
