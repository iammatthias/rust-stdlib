//! Quoting and unquoting, a port of Go's `strconv/quote.go`. Go strings are
//! byte sequences that need not be UTF-8, so these functions work on bytes
//! and follow Go's UTF-8 decoding rules (an invalid byte decodes as U+FFFD
//! with width 1).

use super::Error;
use crate::unicode;
use crate::unicode::rune::{append_rune, decode_rune, valid_rune, RUNE_ERROR};

const LOWERHEX: &[u8; 16] = b"0123456789abcdef";

/// A Unicode code point as Go's `rune` (`int32`). Implemented for `char`,
/// `i32` and `u32` so functions that accept any Go rune, including invalid
/// ones such as surrogates, also accept a `char`.
pub trait Rune: Copy {
    /// The code point as Go's `rune` value.
    fn to_rune(self) -> i32;
}

impl Rune for char {
    fn to_rune(self) -> i32 {
        self as i32
    }
}
impl Rune for i32 {
    fn to_rune(self) -> i32 {
        self
    }
}
impl Rune for u32 {
    fn to_rune(self) -> i32 {
        self as i32
    }
}

fn into_string(v: Vec<u8>) -> String {
    String::from_utf8(v).unwrap_or_default()
}

fn quote_with(s: &[u8], quote: u8, ascii_only: bool, graphic_only: bool) -> String {
    let mut buf = Vec::with_capacity(3 * s.len() / 2);
    appended_quoted_with(&mut buf, s, quote, ascii_only, graphic_only);
    into_string(buf)
}

fn quote_rune_with(r: i32, quote: u8, ascii_only: bool, graphic_only: bool) -> String {
    let mut buf = Vec::new();
    appended_quoted_rune_with(&mut buf, r, quote, ascii_only, graphic_only);
    into_string(buf)
}

fn appended_quoted_with(
    buf: &mut Vec<u8>,
    mut s: &[u8],
    quote: u8,
    ascii_only: bool,
    graphic_only: bool,
) {
    buf.reserve(s.len() + 2);
    buf.push(quote);
    while !s.is_empty() {
        let (r, width) = decode_rune(s);
        if width == 1 && r == RUNE_ERROR {
            buf.extend_from_slice(b"\\x");
            buf.push(LOWERHEX[(s[0] >> 4) as usize]);
            buf.push(LOWERHEX[(s[0] & 0xF) as usize]);
        } else {
            append_escaped_rune(buf, r, quote, ascii_only, graphic_only);
        }
        s = &s[width..];
    }
    buf.push(quote);
}

fn appended_quoted_rune_with(
    buf: &mut Vec<u8>,
    mut r: i32,
    quote: u8,
    ascii_only: bool,
    graphic_only: bool,
) {
    buf.push(quote);
    if !valid_rune(r) {
        r = RUNE_ERROR;
    }
    append_escaped_rune(buf, r, quote, ascii_only, graphic_only);
    buf.push(quote);
}

fn append_escaped_rune(
    buf: &mut Vec<u8>,
    mut r: i32,
    quote: u8,
    ascii_only: bool,
    graphic_only: bool,
) {
    if r == quote as i32 || r == '\\' as i32 {
        // always backslashed
        buf.push(b'\\');
        buf.push(r as u8);
        return;
    }
    if ascii_only {
        if r < 0x80 && is_print(r) {
            buf.push(r as u8);
            return;
        }
    } else if is_print(r) || graphic_only && unicode::is_graphic(r) {
        append_rune(buf, r);
        return;
    }
    match r {
        0x07 => buf.extend_from_slice(b"\\a"),
        0x08 => buf.extend_from_slice(b"\\b"),
        0x0C => buf.extend_from_slice(b"\\f"),
        0x0A => buf.extend_from_slice(b"\\n"),
        0x0D => buf.extend_from_slice(b"\\r"),
        0x09 => buf.extend_from_slice(b"\\t"),
        0x0B => buf.extend_from_slice(b"\\v"),
        _ => {
            if r < ' ' as i32 || r == 0x7f {
                buf.extend_from_slice(b"\\x");
                buf.push(LOWERHEX[((r as u8) >> 4) as usize]);
                buf.push(LOWERHEX[((r as u8) & 0xF) as usize]);
                return;
            }
            if !valid_rune(r) {
                r = 0xFFFD;
            }
            if r < 0x10000 {
                buf.extend_from_slice(b"\\u");
                for s in (0..=12).rev().step_by(4) {
                    buf.push(LOWERHEX[((r >> s) & 0xF) as usize]);
                }
            } else {
                buf.extend_from_slice(b"\\U");
                for s in (0..=28).rev().step_by(4) {
                    buf.push(LOWERHEX[((r >> s) & 0xF) as usize]);
                }
            }
        }
    }
}

/// Returns a double-quoted Go string literal representing s, using Go escape
/// sequences (\t, \n, \xFF, Ā) for control characters and non-printable
/// characters as defined by [`is_print`].
pub fn quote(s: impl AsRef<[u8]>) -> String {
    quote_with(s.as_ref(), b'"', false, false)
}

/// Appends a double-quoted Go string literal representing s, as generated by
/// [`quote`], to dst.
pub fn append_quote(dst: &mut Vec<u8>, s: impl AsRef<[u8]>) {
    appended_quoted_with(dst, s.as_ref(), b'"', false, false);
}

/// Like [`quote`] but escapes all non-ASCII characters.
pub fn quote_to_ascii(s: impl AsRef<[u8]>) -> String {
    quote_with(s.as_ref(), b'"', true, false)
}

/// Appends the result of [`quote_to_ascii`] to dst.
pub fn append_quote_to_ascii(dst: &mut Vec<u8>, s: impl AsRef<[u8]>) {
    appended_quoted_with(dst, s.as_ref(), b'"', true, false);
}

/// Like [`quote`] but leaves Unicode graphic characters, as defined by
/// [`is_graphic`], unchanged.
pub fn quote_to_graphic(s: impl AsRef<[u8]>) -> String {
    quote_with(s.as_ref(), b'"', false, true)
}

/// Appends the result of [`quote_to_graphic`] to dst.
pub fn append_quote_to_graphic(dst: &mut Vec<u8>, s: impl AsRef<[u8]>) {
    appended_quoted_with(dst, s.as_ref(), b'"', false, true);
}

/// Returns a single-quoted Go character literal representing the rune. An
/// invalid code point is interpreted as U+FFFD.
pub fn quote_rune(r: impl Rune) -> String {
    quote_rune_with(r.to_rune(), b'\'', false, false)
}

/// Appends the result of [`quote_rune`] to dst.
pub fn append_quote_rune(dst: &mut Vec<u8>, r: impl Rune) {
    appended_quoted_rune_with(dst, r.to_rune(), b'\'', false, false);
}

/// Like [`quote_rune`] but escapes all non-ASCII characters.
pub fn quote_rune_to_ascii(r: impl Rune) -> String {
    quote_rune_with(r.to_rune(), b'\'', true, false)
}

/// Appends the result of [`quote_rune_to_ascii`] to dst.
pub fn append_quote_rune_to_ascii(dst: &mut Vec<u8>, r: impl Rune) {
    appended_quoted_rune_with(dst, r.to_rune(), b'\'', true, false);
}

/// Like [`quote_rune`] but leaves graphic characters unchanged.
pub fn quote_rune_to_graphic(r: impl Rune) -> String {
    quote_rune_with(r.to_rune(), b'\'', false, true)
}

/// Appends the result of [`quote_rune_to_graphic`] to dst.
pub fn append_quote_rune_to_graphic(dst: &mut Vec<u8>, r: impl Rune) {
    appended_quoted_rune_with(dst, r.to_rune(), b'\'', false, true);
}

/// Reports whether s can be represented unchanged as a single-line backquoted
/// string without control characters other than tab.
pub fn can_backquote(s: impl AsRef<[u8]>) -> bool {
    let mut s = s.as_ref();
    while !s.is_empty() {
        let (r, wid) = decode_rune(s);
        s = &s[wid..];
        if wid > 1 {
            if r == 0xFEFF {
                return false; // BOMs are invisible and should not be quoted.
            }
            continue; // All other multibyte runes are correctly encoded and assumed printable.
        }
        if r == RUNE_ERROR {
            return false;
        }
        if (r < ' ' as i32 && r != '\t' as i32) || r == '`' as i32 || r == 0x7F {
            return false;
        }
    }
    true
}

fn unhex(b: u8) -> Option<i32> {
    match b {
        b'0'..=b'9' => Some((b - b'0') as i32),
        b'a'..=b'f' => Some((b - b'a') as i32 + 10),
        b'A'..=b'F' => Some((b - b'A') as i32 + 10),
        _ => None,
    }
}

/// Decodes the first character or byte in the escaped string or character
/// literal s. It returns the decoded code point or byte value, whether it
/// needs a multibyte UTF-8 representation, and the remainder of s.
///
/// quote is the type of literal being parsed: a single quote permits `\'` and
/// disallows unescaped `'`; a double quote permits `\"` and disallows
/// unescaped `"`; zero permits neither escape and allows both unescaped.
pub fn unquote_char(s: &[u8], quote: u8) -> Result<(u32, bool, &[u8]), Error> {
    // easy cases
    let Some(&c) = s.first() else {
        return Err(Error::Syntax);
    };
    if c == quote && (quote == b'\'' || quote == b'"') {
        return Err(Error::Syntax);
    }
    if c >= 0x80 {
        let (r, size) = decode_rune(s);
        return Ok((r as u32, true, &s[size..]));
    }
    if c != b'\\' {
        return Ok((c as u32, false, &s[1..]));
    }

    // hard case: c is backslash
    if s.len() <= 1 {
        return Err(Error::Syntax);
    }
    let c = s[1];
    let mut s = &s[2..];
    let mut multibyte = false;

    let value: i32 = match c {
        b'a' => 0x07,
        b'b' => 0x08,
        b'f' => 0x0C,
        b'n' => 0x0A,
        b'r' => 0x0D,
        b't' => 0x09,
        b'v' => 0x0B,
        b'x' | b'u' | b'U' => {
            let n = match c {
                b'x' => 2,
                b'u' => 4,
                _ => 8,
            };
            if s.len() < n {
                return Err(Error::Syntax);
            }
            let mut v: i32 = 0;
            for &h in &s[..n] {
                let x = unhex(h).ok_or(Error::Syntax)?;
                v = v.wrapping_shl(4) | x;
            }
            s = &s[n..];
            if c != b'x' {
                if !valid_rune(v) {
                    return Err(Error::Syntax);
                }
                multibyte = true;
            }
            // \x: single-byte string, possibly not UTF-8
            v
        }
        b'0'..=b'7' => {
            let mut v = (c - b'0') as i32;
            if s.len() < 2 {
                return Err(Error::Syntax);
            }
            for &d in &s[..2] {
                // one digit already; two more
                let x = d as i32 - b'0' as i32;
                if !(0..=7).contains(&x) {
                    return Err(Error::Syntax);
                }
                v = (v << 3) | x;
            }
            s = &s[2..];
            if v > 255 {
                return Err(Error::Syntax);
            }
            v
        }
        b'\\' => '\\' as i32,
        b'\'' | b'"' => {
            if c != quote {
                return Err(Error::Syntax);
            }
            c as i32
        }
        _ => return Err(Error::Syntax),
    };
    Ok((value as u32, multibyte, s))
}

/// Returns the quoted string (as understood by [`unquote`]) at the prefix of s.
pub fn quoted_prefix<S: AsRef<[u8]> + ?Sized>(s: &S) -> Result<&[u8], Error> {
    let s = s.as_ref();
    unquote_impl(s, false).map(|(_, end)| &s[..end])
}

/// Interprets s as a single-quoted, double-quoted, or backquoted Go string
/// literal, returning the bytes that s quotes. (A single-quoted literal yields
/// its one character; an empty character literal yields no bytes.) The result
/// may not be valid UTF-8, as in Go.
pub fn unquote(s: impl AsRef<[u8]>) -> Result<Vec<u8>, Error> {
    let s = s.as_ref();
    let (out, end) = unquote_impl(s, true)?;
    if end < s.len() {
        return Err(Error::Syntax);
    }
    Ok(out)
}

/// Parses a quoted string at the start of the input, returning the (optionally
/// unescaped) contents and the number of input bytes consumed.
fn unquote_impl(input: &[u8], unescape: bool) -> Result<(Vec<u8>, usize), Error> {
    // Determine the quote form and optimistically find the terminating quote.
    if input.len() < 2 {
        return Err(Error::Syntax);
    }
    let quote = input[0];
    let Some(end) = input[1..].iter().position(|&c| c == quote) else {
        return Err(Error::Syntax);
    };
    let end = end + 2; // position after terminating quote; may be wrong if escape sequences are present
    let head = &input[..end];

    match quote {
        b'`' => {
            let out = if !unescape {
                head.to_vec() // include quotes
            } else {
                // Carriage returns inside raw string literals are discarded.
                head[1..end - 1]
                    .iter()
                    .copied()
                    .filter(|&c| c != b'\r')
                    .collect()
            };
            Ok((out, end))
        }
        b'"' | b'\'' => {
            // Handle quoted strings without any escape sequences.
            if !head.contains(&b'\\') && !head.contains(&b'\n') {
                let inner = &input[1..end - 1];
                let valid = if quote == b'"' {
                    std::str::from_utf8(inner).is_ok()
                } else {
                    let (r, n) = decode_rune(inner);
                    1 + n + 1 == end && (r != RUNE_ERROR || n != 1)
                };
                if valid {
                    let out = if unescape {
                        inner.to_vec()
                    } else {
                        head.to_vec()
                    };
                    return Ok((out, end));
                }
            }

            // Handle quoted strings with escape sequences.
            let mut buf = Vec::new();
            let mut rest = &input[1..]; // skip starting quote
            while !rest.is_empty() && rest[0] != quote {
                // Process the next character, rejecting any unescaped newline
                // characters which are invalid.
                let first = rest[0];
                let (r, multibyte, tail) = unquote_char(rest, quote)?;
                if first == b'\n' {
                    return Err(Error::Syntax);
                }
                rest = tail;

                // Append the character if unescaping the input.
                if unescape {
                    if r < 0x80 || !multibyte {
                        buf.push(r as u8);
                    } else {
                        append_rune(&mut buf, r as i32);
                    }
                }

                // Single quoted strings must be a single character.
                if quote == b'\'' {
                    break;
                }
            }

            // Verify that the string ends with a terminating quote.
            if rest.first() != Some(&quote) {
                return Err(Error::Syntax);
            }
            let consumed = input.len() - rest.len() + 1; // include terminating quote
            if unescape {
                Ok((buf, consumed))
            } else {
                Ok((input[..consumed].to_vec(), consumed))
            }
        }
        _ => Err(Error::Syntax),
    }
}

/// Reports whether the rune is defined as printable by Go, with the same
/// definition as Go's `unicode.IsPrint`: letters, numbers, punctuation,
/// symbols and ASCII space.
pub fn is_print(r: impl Rune) -> bool {
    unicode::is_print(r.to_rune())
}

/// Reports whether the rune is defined as a Graphic by Unicode: letters,
/// marks, numbers, punctuation, symbols, and spaces (categories L, M, N, P, S
/// and Zs).
pub fn is_graphic(r: impl Rune) -> bool {
    unicode::is_graphic(r.to_rune())
}
